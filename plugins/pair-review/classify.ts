/**
 * Решение о втором мозге: нужен ли задаче независимый проверяющий и какой.
 *
 * Правила выведены из независимых работ и из ретроспективы этой машины, а не из
 * вкуса. Коротко, что заставило их быть именно такими:
 *
 * - Второй агент окупается как ВЕРИФИКАТОР, а не как второй сочинитель:
 *   проверить дешевле, чем создать. Повторная генерация выигрыша не даёт.
 * - Он должен быть ДРУГОГО семейства. В разборе ста провалов многоагентного
 *   обмена 65% приходится на «коллективное заблуждение» однородных агентов:
 *   они усиливают общую ошибку вместо того, чтобы её ловить.
 * - На задачах, где базовая точность и так около 90% (рутина, форматирование,
 *   короткий ответ), добавка почти нулевая, а лимит подписки тратится.
 * - Лимит реален: 06.09.2026 подписка Codex закончилась на седьмом треде за
 *   день. Пара на КАЖДЫЙ тред сожгла бы её к обеду, и проверяющего не осталось
 *   бы там, где ошибка стоит денег клиента.
 *
 * Ретроспектива по 105 дочерним тредам этой машины: существенную находку дали
 * не меньше 35, пустыми оказались 8-10, и почти все дорогие находки лежат в
 * шести классах ниже (деньги и обещания клиенту, сдача артефакта человеку,
 * диагностика инцидента, изменение общей системы, пачка правок владельца,
 * необратимое действие).
 */

export type TaskClass =
  | "деньги-и-обещания"
  | "сдача-артефакта"
  | "диагностика"
  | "общая-система"
  | "правки-владельца"
  | "необратимое"
  | "рутина";

export interface PairDecision {
  /** Запускать ли независимого проверяющего. */
  pair: boolean;
  taskClass: TaskClass;
  /** Провайдер проверяющего: всегда другого семейства, чем родитель. */
  provider?: string;
  model?: string;
  reasoningLevel?: "medium" | "high" | "xhigh";
  /** Сколько раундов обмена максимум. Второй раунд — только при расхождении. */
  maxRounds?: number;
  /** Человеческое объяснение, попадает в карточку проверки. */
  why: string;
}

interface ClassifyArgs {
  /** Первый запрос человека в треде: по нему судим о задаче. */
  prompt: string;
  title?: string;
  /** Провайдер родительского треда. */
  parentProvider: string;
}

// Границы слов заданы юникодным просмотром назад, а не \b: в JavaScript \b
// опирается на ASCII-класс \w, поэтому перед кириллицей она не срабатывает
// вовсе, и все признаки молча не находились (поймано тестами 07.09.2026).
const ПРИЗНАКИ: ReadonlyArray<{ класс: TaskClass; слова: RegExp }> = [
  {
    класс: "деньги-и-обещания",
    слова:
      /(?<![\p{L}])(цена|стоимость|сумма|бюджет|оплат|счёт|счет|договор|гарант|возврат|окупаем|маржа|выручка|прибыл|скидк|тариф|смет|оффер|зарплат|вознаграждени)/iu,
  },
  {
    класс: "диагностика",
    слова:
      /(?<![\p{L}])(почему|не работает|сломал|упал|падает|ошибк|дефект|баг|регресс|разберись|расследуй|инцидент|обрыв|(?:проверь|проверить|перепроверь|прими)\s*[,]?\s*(?:мне\s+)?(?:вс[её]|все|весь|выполн|работа|сдела|корректн|правильн|готов)|вс[её]\s+ли\s+\p{L}+\s+(?:выполн|работа|сдела|готов|закрыт)|приёмк|приемк)/iu,
  },
  {
    класс: "общая-система",
    слова:
      /(?<![\p{L}])(правил|регламент|стандарт|методолог|замок|гейт|хук|конвейер|систем(?:ный|ная) фикс|навык|инструкц|шаблон для|во всех|всегда должн|(?:во|на|со|для|у)\s+вс[еиюяё]\p{L}*\s+(?:мо\p{L}+\s+)?(?:тред|проект|систем|платформ|сесси|мест|случа|треда|проекта)|вс[юей]\p{L}*\s+(?:мо\p{L}+\s+)?систем)/iu,
  },
  {
    класс: "необратимое",
    слова:
      /(?<![\p{L}])(удали(?:те)?(?![\p{L}])|снеси|очисти\p{L}*\s+(?:баз|кэш|кеш|папк|диск|таблиц|индекс|лог|историю|данн)|перенеси|мигра|выкат|задеплой|деплой|прод(?![\p{L}])|продакшен|опубликуй|разошли|отправь клиент|rm -rf|drop table|force push|(?:убери|откати|отмени|верни)\s+(?:сво|вс[её]|мо[её]|эт|назад|как\s+было|правк|изменени|работу|коммит)|ничего\s+не\s+трон)/iu,
  },
  {
    класс: "сдача-артефакта",
    слова:
      /(?<![\p{L}])(собери(?:те)?(?![\p{L}])|сверстай|подготовь|документ|презентац|docx|xlsx|таблиц|отчёт|отчет|карт[ау] внедрения|стандарт блока|пост(?![\p{L}])|письмо|карусель|лендинг|сдай(?:те)?(?![\p{L}])|сдача)/iu,
  },
  {
    класс: "правки-владельца",
    слова:
      /(?<![\p{L}])(правк|замечани|переделай|исправь всё|список правок|вот скриншот|не нравится|плохо получилось)/iu,
  },
];

const РУТИНА =
  /^\s*(покажи|найди файл|открой|запусти|перезапусти|статус|проверь статус|сколько|когда|где лежит|переименуй|скопируй|список|ls|cat)(?![\p{L}])/iu;

/**
 * Классы, которые надо проверять ПАРАЛЛЕЛЬНО с работой автора, а не после неё.
 *
 * Разбор 07.09.2026 сначала качнулся в одну сторону, потом в другую. На
 * завершении хода находки о необратимом действии приходят, когда удаление уже
 * случилось. Но параллельный запуск для ВСЕХ классов даёт зеркальную беду:
 * проверяющий смотрит рабочую папку до того, как автор что-то сделал, и на
 * сдаче артефакта проверяет пустое место. Поэтому рано запускается только то,
 * где важно успеть предупредить; остальное ждёт готового результата.
 */
export const РАННИЕ_КЛАССЫ: ReadonlySet<TaskClass> = new Set<TaskClass>([
  "необратимое",
]);

/** Проверять эту задачу параллельно с работой автора? */
export function проверятьРано(класс: TaskClass): boolean {
  return РАННИЕ_КЛАССЫ.has(класс);
}

/** Классы, где ошибка дороже любой экономии на модели проверяющего. */
const ДОРОГИЕ: ReadonlySet<TaskClass> = new Set<TaskClass>([
  "деньги-и-обещания",
  "необратимое",
  "диагностика",
]);

/** Мощность и число раундов под класс: дорогая ошибка — больше мощности. */
const ПОД_КЛАСС: Record<
  Exclude<TaskClass, "рутина">,
  { reasoningLevel: "medium" | "high" | "xhigh"; maxRounds: number; why: string }
> = {
  "деньги-и-обещания": {
    reasoningLevel: "xhigh",
    maxRounds: 2,
    why: "число или обещание уходит человеку: ошибка стоит денег и доверия",
  },
  необратимое: {
    reasoningLevel: "xhigh",
    maxRounds: 2,
    why: "действие необратимо: проверка дешевле отката",
  },
  диагностика: {
    reasoningLevel: "xhigh",
    maxRounds: 2,
    why: "диагностика: вторая модель ищет иначе и ловит причину, которую первая пропускает",
  },
  "общая-система": {
    reasoningLevel: "high",
    maxRounds: 1,
    why: "правка общей системы действует на все будущие задачи",
  },
  "сдача-артефакта": {
    reasoningLevel: "high",
    maxRounds: 1,
    why: "артефакт увидит человек: проверка фактов и вида до сдачи",
  },
  "правки-владельца": {
    reasoningLevel: "high",
    maxRounds: 1,
    why: "пачка правок владельца: легко закрыть букву и потерять смысл",
  },
};

/**
 * Проверяющий: всегда другого семейства, чем автор, и по мощности — под класс.
 *
 * Раньше здесь стояли только старшие модели, независимо от задачи. Замер по
 * живой базе 07.09.2026 объясняет, почему это дорого: средний ход в системе
 * стоит 2,8 млн токенов, а на проверку приходится ещё один тред. Ставить
 * старшую модель на разбор вёрстки значит платить за неё столько же, сколько
 * за разбор денег клиента.
 *
 * Дорогие классы (деньги, необратимое, диагностика) сохраняют старшую модель:
 * там ошибка стоит больше, чем вся экономия. Остальные идут на среднюю.
 */
export function verifierFor(
  parentProvider: string,
  класс?: TaskClass,
): { provider: string; model: string } | undefined {
  const дорогой = класс === undefined || ДОРОГИЕ.has(класс);
  if (parentProvider === "claude-code" || parentProvider === "anthropic") {
    return {
      provider: "codex",
      model: дорогой ? "gpt-6-astra" : "gpt-5.6-sol",
    };
  }
  if (parentProvider === "codex") {
    return {
      provider: "claude-code",
      model: дорогой ? "claude-opus-5[1m]" : "claude-sonnet-5",
    };
  }
  return undefined;
}

export function classifyTask(args: ClassifyArgs): PairDecision {
  const текст = `${args.title ?? ""}\n${args.prompt}`.trim();
  const найден = ПРИЗНАКИ.find((признак) => признак.слова.test(текст));
  const проверяющий = verifierFor(args.parentProvider, найден?.класс);

  // Рутину отсекаем только когда признаков дорогой ошибки нет вовсе: иначе
  // «покажи, как считается возврат по гарантии» ушло бы в рутину из-за первого
  // слова, хотя это деньги клиента.
  if (текст.length === 0 || (найден === undefined && РУТИНА.test(args.prompt))) {
    return {
      pair: false,
      taskClass: "рутина",
      why: "рутина с высокой базовой точностью: второй агент почти ничего не добавляет, а лимит тратит",
    };
  }

  if (найден === undefined) {
    return {
      pair: false,
      taskClass: "рутина",
      why: "признаков дорогой ошибки не видно",
    };
  }
  if (проверяющий === undefined) {
    return {
      pair: false,
      taskClass: найден.класс,
      why: `для провайдера ${args.parentProvider} проверяющий другого семейства не задан`,
    };
  }

  const настройка = ПОД_КЛАСС[найден.класс as Exclude<TaskClass, "рутина">];
  return {
    pair: true,
    taskClass: найден.класс,
    provider: проверяющий.provider,
    model: проверяющий.model,
    reasoningLevel: настройка.reasoningLevel,
    maxRounds: настройка.maxRounds,
    why: настройка.why,
  };
}
