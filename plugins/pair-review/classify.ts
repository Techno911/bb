const РУТИНА =
  /^\s*(покажи|найди файл|открой|запусти|перезапусти|статус|проверь статус|сколько|когда|где лежит|переименуй|скопируй|список|ls|cat)(?![\p{L}])/iu;

/**
 * Классы, которые надо проверять ПАРАЛЛЕЛЬНО с работой автора, а не после неё.
 *
 * Разбор 07.09.2026 сначала качнулся в одну сторону, потом в другую. На
 * завершении хода находки о необратимом действии приходят, когда удаление уже
 * случилось. Но параллельный запуск для ВСЕХ классов даёт зеркальную беду:
 * проверяющий смотрит рабочую папку до того, как автор что-то сделал, и на
 * сдаче артефакта проверяет пустое место. Поэтому рано запускается только то,
 * где важно успеть предупредить; остальное ждёт готового результата.
 */
export const РАННИЕ_КЛАССЫ: ReadonlySet<TaskClass> = new Set<TaskClass>([
  "необратимое",
]);

/**
 * Нужен ли запуск в этот момент.
 *
 * «После» верно ВСЕГДА, включая необратимое: ранний проверяющий видел рабочую
 * папку до действия, и его «расхождений не нашёл» об итоге не говорит ничего.
 * «Рано» — только там, где важно успеть предупредить.
 */
export function запускатьВМомент(
  класс: TaskClass,
  момент: "рано" | "после",
): boolean {
  return момент === "после" ? true : проверятьРано(класс);
}

/** Проверять эту задачу параллельно с работой автора? */
export function проверятьРано(класс: TaskClass): boolean {
  return РАННИЕ_КЛАССЫ.has(класс);
}

/** Классы, где ошибка дороже любой экономии на модели проверяющего. */
const ДОРОГИЕ: ReadonlySet<TaskClass> = new Set<TaskClass>([
  "деньги-и-обещания",
  "необратимое",
  "диагностика",
]);

/** Мощность и число раундов под класс: дорогая ошибка — больше мощности. */
const ПОД_КЛАСС: Record<
  Exclude<TaskClass, "рутина">,
  { reasoningLevel: "medium" | "high" | "xhigh"; maxRounds: number; why: string }
> = {
  "деньги-и-обещания": {
    reasoningLevel: "xhigh",
    maxRounds: 2,
    why: "число или обещание уходит человеку: ошибка стоит денег и доверия",
  },
  необратимое: {
    reasoningLevel: "xhigh",
    maxRounds: 2,
    why: "действие необратимо: проверка дешевле отката",
  },
  диагностика: {
    reasoningLevel: "xhigh",
    maxRounds: 2,
    why: "диагностика: вторая модель ищет иначе и ловит причину, которую первая пропускает",
  },
  "общая-система": {
    reasoningLevel: "high",
    maxRounds: 1,
    why: "правка общей системы действует на все будущие задачи",
  },
  "сдача-артефакта": {
    reasoningLevel: "high",
    maxRounds: 1,
    why: "артефакт увидит человек: проверка фактов и вида до сдачи",
  },
  "правки-владельца": {
    reasoningLevel: "high",
    maxRounds: 1,
    why: "пачка правок владельца: легко закрыть букву и потерять смысл",
  },
};

/**
 * Семейство модели. Определяется по МОДЕЛИ, а не по провайдеру, потому что
 * Cursor и Pi это оболочки: за ними стоит любая модель, и провайдер о её
 * происхождении не говорит ничего.
 *
 * Проверено 09.09.2026: в bb зарегистрированы четыре провайдера
 * (claude-code, codex, pi, acp-cursor), а пара знала два. Для остальных
 * verifierFor возвращал undefined, то есть тред на новом провайдере остался
 * бы без проверки МОЛЧА — тот же класс, что покрытие, привязанное к месту в
 * сайдбаре.
 */
export type Семейство = "anthropic" | "openai" | "google" | "xai" | "иное";

export function семействоМодели(модель: string | undefined): Семейство {
  const м = (модель ?? "").toLowerCase();
  if (/(claude|opus|sonnet|haiku|fable)/.test(м)) return "anthropic";
  if (/(gpt|codex|^o[0-9])/.test(м)) return "openai";
  if (/gemini/.test(м)) return "google";
  if (/grok/.test(м)) return "xai";
  return "иное";
}

/**
 * Семейство по провайдеру, когда модель неизвестна.
 *
 * ⚠️ Известна она почти никогда: лента и `threads.get` в SDK модель треда не
 * отдают вовсе (проверено 09.09.2026, есть только providerId). Параметр
 * `parentModel` оставлен рабочим и покрыт тестами на случай, когда поле
 * появится либо когда вызывающий знает модель сам; сейчас решение почти всегда
 * идёт по провайдеру.
 *
 * Отсюда честная граница: у ОБОЛОЧЕК (pi, acp-cursor) семейство неизвестно, и
 * проверяющим назначается Anthropic. Если за оболочкой стоит Claude, пара
 * выйдет однородной — это слабее разнородной, но лучше молчания, которое было
 * до этого.
 */
function семействоПровайдера(провайдер: string): Семейство {
  if (провайдер === "claude-code" || провайдер === "anthropic") return "anthropic";
  if (провайдер === "codex") return "openai";
  return "иное";
}

/**
 * Проверяющий: всегда другого семейства, чем автор, и по мощности — под класс.
 *
 * Мощность идёт от класса: замер по живой базе 07.09.2026 показал, что средний
 * ход стоит 2,8 млн токенов, и ставить старшую модель на разбор вёрстки значит
 * платить за неё столько же, сколько за разбор денег клиента. Дорогие классы
 * (деньги, необратимое, диагностика) сохраняют старшую модель.
 *
 * Семейство считается по модели родителя, если она известна: тред на Cursor с
 * моделью Claude обязан проверяться моделью OpenAI, а не ещё одним Claude,
 * иначе получается однородная пара, которая усиливает общую ошибку вместо того,
 * чтобы её ловить.
 */
export function verifierFor(
  parentProvider: string,
  класс?: TaskClass,
  parentModel?: string,
): { provider: string; model: string } | undefined {
  const дорогой = класс === undefined || ДОРОГИЕ.has(класс);
  const семья =
    parentModel !== undefined && семействоМодели(parentModel) !== "иное"
      ? семействоМодели(parentModel)
      : семействоПровайдера(parentProvider);

  // От автора-Anthropic проверяет OpenAI, от всех остальных семейств
  // (OpenAI, Google, xAI, неизвестное) проверяет Anthropic. Так пара
  // разнородна при любом провайдере, включая оболочки.
  if (семья === "anthropic") {
    return { provider: "codex", model: дорогой ? "gpt-6-astra" : "gpt-5.6-sol" };
  }
  return {
    provider: "claude-code",
    model: дорогой ? "claude-opus-5[1m]" : "claude-sonnet-5",
  };
}

export function classifyTask(args: ClassifyArgs): PairDecision {
  const текст = `${args.title ?? ""}\n${args.prompt}`.trim();
  const найден = ПРИЗНАКИ.find((признак) => признак.слова.test(текст));
  const проверяющий = verifierFor(
    args.parentProvider,
    найден?.класс,
    args.parentModel,
  );

  // Рутину отсекаем только когда признаков дорогой ошибки нет вовсе: иначе
  // «покажи, как считается возврат по гарантии» ушло бы в рутину из-за первого
  // слова, хотя это деньги клиента.
  if (текст.length === 0 || (найден === undefined && РУТИНА.test(args.prompt))) {
    return {
      pair: false,
      taskClass: "рутина",
      why: "рутина с высокой базовой точностью: второй агент почти ничего не добавляет, а лимит тратит",
    };
  }

  if (найден === undefined) {
    return {
      pair: false,
      taskClass: "рутина",
      why: "признаков дорогой ошибки не видно",
    };
  }
  if (проверяющий === undefined) {
    return {
      pair: false,
      taskClass: найден.класс,
      why: `для провайдера ${args.parentProvider} проверяющий другого семейства не задан`,
    };
  }

  const настройка = ПОД_КЛАСС[найден.класс as Exclude<TaskClass, "рутина">];
  return {
    pair: true,
    taskClass: найден.класс,
    provider: проверяющий.provider,
    model: проверяющий.model,
    reasoningLevel: настройка.reasoningLevel,
    maxRounds: настройка.maxRounds,
    why: настройка.why,
  };
}
