import { describe, expect, it } from "vitest";

import { classifyTask, сВзглядомНаЛимиты, ступенью } from "./classify.js";
import {
  балансЛимитов,
  недельныйРасход,
  провайдерЛимитов,
  type СнимокЛимитов,
} from "./limits-balance.js";
import { кандидаты, разобратьСнимок, создатьИсточник } from "./limits-source.js";

const СЕЙЧАС = Date.UTC(2026, 8, 14, 12, 0, 0);
const ПЯТЬ_ДНЕЙ = СЕЙЧАС + 5 * 24 * 60 * 60 * 1000;

function снимок(claude: number, codex: number, опции?: {
  сбросClaude?: number;
  сбросCodex?: number;
  обновлено?: number;
}): СнимокЛимитов {
  return {
    провайдеры: [
      {
        провайдер: "claude",
        подпись: "Claude",
        окна: [
          { ключ: "session", подпись: "5 часов", процент: 90, сбросВ: СЕЙЧАС + 3_600_000, важность: "normal" },
          { ключ: "weekly_all", подпись: "Неделя", процент: claude, сбросВ: опции?.сбросClaude ?? ПЯТЬ_ДНЕЙ, важность: "normal" },
          { ключ: "weekly_scoped", подпись: "Неделя Fable", процент: 4, сбросВ: опции?.сбросClaude ?? ПЯТЬ_ДНЕЙ, важность: "normal" },
        ],
        ошибка: null,
        снято: СЕЙЧАС,
      },
      {
        провайдер: "codex",
        подпись: "Codex",
        окна: [
          { ключ: "primary", подпись: "Неделя", процент: codex, сбросВ: опции?.сбросCodex ?? ПЯТЬ_ДНЕЙ, важность: null },
        ],
        ошибка: null,
        снято: СЕЙЧАС,
      },
    ],
    обновлено: опции?.обновлено ?? СЕЙЧАС,
  };
}

describe("недельный расход", () => {
  it("берёт самое загруженное недельное окно, а не пятичасовое", () => {
    const расход = недельныйРасход(снимок(13, 34).провайдеры[0], СЕЙЧАС);
    expect(расход?.процент).toBe(13);
  });

  it("не считает расходом окно, чей срок сброса уже наступил", () => {
    const с = снимок(99, 34, { сбросClaude: СЕЙЧАС - 1000 });
    expect(недельныйРасход(с.провайдеры[0], СЕЙЧАС)).toBeNull();
  });

  it("узнаёт недельное окно Codex по подписи: ключ у него primary", () => {
    expect(недельныйРасход(снимок(13, 34).провайдеры[1], СЕЙЧАС)?.процент).toBe(34);
  });

  it("знает, чей расход смотреть для провайдера треда", () => {
    expect(провайдерЛимитов("claude-code")).toBe("claude");
    expect(провайдерЛимитов("codex")).toBe("codex");
    expect(провайдерЛимитов("acp-cursor")).toBeNull();
  });
});

describe("паритет лимитов", () => {
  it("разница в пределах допуска ничего не меняет", () => {
    const баланс = балансЛимитов({
      снимок: снимок(30, 34),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("паритет");
    expect(баланс.разрыв).toBe(4);
  });

  it("живой случай 14.09.2026: 13% у Claude против 34% у Codex это сильный перекос", () => {
    const баланс = балансЛимитов({
      снимок: снимок(13, 34),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("беречь-сильно");
    expect(баланс.разрыв).toBe(21);
  });

  it("перекос чуть выше допуска включает бережливость без отказов", () => {
    const баланс = балансЛимитов({
      снимок: снимок(20, 31),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("беречь");
  });

  it("отставание проверяющего разрешает тратить его лимит свободнее", () => {
    const баланс = балансЛимитов({
      снимок: снимок(40, 12),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("догружать");
  });

  it("почти выбранный лимит проверяющего останавливает запуск вовсе", () => {
    const баланс = балансЛимитов({
      снимок: снимок(20, 97),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("стоп");
  });

  it("перекос не считается, если окно перегруженного закрывается через пару часов", () => {
    const баланс = балансЛимитов({
      снимок: снимок(13, 60, { сбросCodex: СЕЙЧАС + 2 * 3_600_000 }),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("паритет");
  });

  it("устаревший снимок решение не меняет: неизвестность не выключает пару", () => {
    const баланс = балансЛимитов({
      снимок: снимок(13, 90, { обновлено: СЕЙЧАС - 60 * 60 * 1000 }),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });
    expect(баланс.режим).toBe("неизвестно");
  });

  it("отсутствие снимка это тоже неизвестность, а не запрет", () => {
    expect(
      балансЛимитов({
        снимок: null,
        провайдерАвтора: "claude-code",
        провайдерПроверяющего: "codex",
        сейчас: СЕЙЧАС,
      }).режим,
    ).toBe("неизвестно");
  });

  it("пара, чей расход не измеряется, остаётся без поправки", () => {
    expect(
      балансЛимитов({
        снимок: снимок(13, 34),
        провайдерАвтора: "acp-cursor",
        провайдерПроверяющего: "claude-code",
        сейчас: СЕЙЧАС,
      }).режим,
    ).toBe("неизвестно");
  });
});

describe("решение с поправкой на лимиты", () => {
  const деньги = () =>
    classifyTask({
      prompt: "посчитай сумму возврата по гарантии для клиента и собери смету",
      parentProvider: "claude-code",
    });
  const артефакт = () =>
    classifyTask({
      prompt: "собери документ для клиента и сдай ссылкой",
      parentProvider: "claude-code",
    });
  const баланс = (claude: number, codex: number) =>
    балансЛимитов({
      снимок: снимок(claude, codex),
      провайдерАвтора: "claude-code",
      провайдерПроверяющего: "codex",
      сейчас: СЕЙЧАС,
    });

  it("при паритете модель прежняя", () => {
    const итог = сВзглядомНаЛимиты(деньги(), баланс(30, 34));
    expect(итог.model).toBe("gpt-6-astra");
    expect(итог.pair).toBe(true);
  });

  it("перекос понижает ступень: деньги проверяет 5.6 Sol вместо GPT-6", () => {
    const итог = сВзглядомНаЛимиты(деньги(), баланс(20, 31));
    expect(итог.pair).toBe(true);
    expect(итог.model).toBe("gpt-5.6-sol");
    expect(итог.reasoningLevel).toBe("xhigh");
  });

  it("сильный перекос снимает мощность, но дорогой класс всё равно проверяется", () => {
    const итог = сВзглядомНаЛимиты(деньги(), баланс(13, 34));
    expect(итог.pair).toBe(true);
    expect(итог.model).toBe("gpt-5.6-sol");
    expect(итог.reasoningLevel).toBe("high");
  });

  it("сильный перекос снимает дешёвый класс до выравнивания", () => {
    const итог = сВзглядомНаЛимиты(артефакт(), баланс(13, 34));
    expect(итог.pair).toBe(false);
    expect(итог.why).toContain("21 п.п.");
  });

  it("выбранный лимит проверяющего отменяет даже деньги: тред всё равно упадёт", () => {
    const итог = сВзглядомНаЛимиты(деньги(), баланс(20, 97));
    expect(итог.pair).toBe(false);
  });

  it("отставший проверяющий догружается старшей моделью на дешёвом классе", () => {
    const итог = сВзглядомНаЛимиты(артефакт(), баланс(40, 12));
    expect(итог.pair).toBe(true);
    expect(итог.model).toBe("gpt-6-astra");
  });

  it("догрузка не трогает дорогой класс: там старшая модель и так стоит", () => {
    const итог = сВзглядомНаЛимиты(деньги(), баланс(40, 12));
    expect(итог.model).toBe("gpt-6-astra");
  });

  it("автор на Codex бережёт Claude тем же правилом, в обратную сторону", () => {
    const первичное = classifyTask({
      prompt: "посчитай сумму возврата по гарантии для клиента",
      parentProvider: "codex",
    });
    expect(первичное.model).toBe("claude-opus-5[1m]");
    const итог = сВзглядомНаЛимиты(
      первичное,
      балансЛимитов({
        снимок: снимок(60, 20),
        провайдерАвтора: "codex",
        провайдерПроверяющего: "claude-code",
        сейчас: СЕЙЧАС,
      }),
    );
    expect(итог.model).toBe("claude-sonnet-5");
  });

  it("рутину лимиты не оживляют", () => {
    const рутина = classifyTask({ prompt: "покажи список файлов", parentProvider: "claude-code" });
    expect(сВзглядомНаЛимиты(рутина, баланс(40, 12)).pair).toBe(false);
  });

  it("ступени знает только тот провайдер, который у нас есть", () => {
    expect(ступенью("codex", "gpt-6-astra", "ниже")).toBe("gpt-5.6-sol");
    expect(ступенью("claude-code", "claude-sonnet-5", "выше")).toBe("claude-opus-5[1m]");
    expect(ступенью("acp-cursor", "что-то", "ниже")).toBe("что-то");
  });
});

describe("источник расхода", () => {
  it("читает снимок командой плагина лимитов", async () => {
    const вызовы: string[][] = [];
    const источник = создатьИсточник({
      запуск: async (файл, аргументы) => {
        вызовы.push([файл, ...аргументы]);
        return { stdout: JSON.stringify(снимок(13, 34)) };
      },
      часы: () => СЕЙЧАС,
    });
    const итог = await источник();
    expect(итог.снимок?.провайдеры).toHaveLength(2);
    expect(итог.причина).toBeNull();
    expect(вызовы[0]?.slice(-3)).toEqual(["limits", "show", "--json"]);
  });

  it("первым пробует свой node с путём к CLI: в плагин-хосте node нет в PATH", () => {
    const список = кандидаты({ BB_CLI: "/путь/bb" } as NodeJS.ProcessEnv, "/узел/node");
    expect(список[0]).toEqual({ файл: "/узел/node", аргументы: ["/путь/bb"] });
    expect(список.at(-1)).toEqual({ файл: "bb", аргументы: [] });
  });

  it("без BB_CLI остаётся обычный путь через PATH", () => {
    expect(кандидаты({} as NodeJS.ProcessEnv, "/узел/node")).toEqual([
      { файл: "bb", аргументы: [] },
    ]);
  });

  it("не спрашивает дважды в пределах кэша", async () => {
    let раз = 0;
    const источник = создатьИсточник({
      запуск: async () => {
        раз += 1;
        return { stdout: JSON.stringify(снимок(13, 34)) };
      },
      часы: () => СЕЙЧАС,
    });
    await источник();
    await источник();
    expect(раз).toBe(1);
  });

  it("сбой команды не роняет пару: расход просто неизвестен", async () => {
    const источник = создатьИсточник({
      запуск: async () => {
        throw new Error("bb не найден");
      },
      часы: () => СЕЙЧАС,
    });
    const итог = await источник();
    expect(итог.снимок).toBeNull();
    expect(итог.причина).toContain("bb не найден");
  });

  it("мусор вместо JSON читается как отсутствие данных", () => {
    expect(разобратьСнимок("не json")).toBeNull();
    expect(разобратьСнимок(JSON.stringify({ что: "то" }))).toBeNull();
  });
});
