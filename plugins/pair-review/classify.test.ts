import { describe, expect, it } from "vitest";

import {
  classifyTask,
  семействоМодели,
  запускатьВМомент,
  проверятьРано,
  verifierFor,
} from "./classify.js";

describe("решение о втором мозге", () => {
  it("зовёт проверяющего там, где ошибка стоит денег", () => {
    const решение = classifyTask({
      prompt: "посчитай сумму возврата по гарантии для клиента и собери смету",
      parentProvider: "claude-code",
    });
    expect(решение.pair).toBe(true);
    expect(решение.taskClass).toBe("деньги-и-обещания");
    expect(решение.reasoningLevel).toBe("xhigh");
    expect(решение.maxRounds).toBe(2);
  });

  it("правка самой системы это общая-система, а не рутина", () => {
    // 14.09.2026: «доработать систему в части ... плагин решает» уходило в
    // рутину, то есть задача про устройство пары оставалась без пары.
    for (const запрос of [
      "Нужно доработать систему в части выбора второго мозга",
      "почини механизм, плагин решает неправильно",
    ]) {
      const решение = classifyTask({ prompt: запрос, parentProvider: "claude-code" });
      expect(решение.taskClass).toBe("общая-система");
    }
  });

  it("зовёт проверяющего на диагностике: вторая модель ищет иначе", () => {
    const решение = classifyTask({
      prompt: "почему упали треды, разберись что сломалось",
      parentProvider: "claude-code",
    });
    expect(решение.pair).toBe(true);
    expect(решение.taskClass).toBe("диагностика");
  });

  it("молчит на рутине: там базовая точность и так высокая", () => {
    for (const запрос of [
      "покажи статус сервера",
      "найди файл с настройками",
      "переименуй папку в архив",
    ]) {
      const решение = classifyTask({ prompt: запрос, parentProvider: "claude-code" });
      expect(решение.pair, запрос).toBe(false);
      expect(решение.taskClass, запрос).toBe("рутина");
    }
  });

  it("проверяющий всегда другого семейства", () => {
    expect(verifierFor("claude-code")?.provider).toBe("codex");
    expect(verifierFor("codex")?.provider).toBe("claude-code");
    // Однородная пара запрещена по данным: 65% провалов многоагентного обмена
    // это «коллективное заблуждение» агентов одного рода.
    expect(verifierFor("claude-code")?.provider).not.toBe("claude-code");
    expect(verifierFor("codex")?.provider).not.toBe("codex");
  });

  it("мощность проверяющего зависит от класса, а не всегда старшая", () => {
    // Найдено проверяющим 07.09.2026: verifierFor всегда возвращал старшую
    // модель, поэтому перевод основной работы на дешёвую не уменьшал стоимость
    // автоматически добавляемой проверки.
    expect(verifierFor("claude-code", "деньги-и-обещания")?.model).toBe("gpt-6-astra");
    expect(verifierFor("claude-code", "необратимое")?.model).toBe("gpt-6-astra");
    expect(verifierFor("claude-code", "сдача-артефакта")?.model).toBe("gpt-5.6-sol");
    expect(verifierFor("claude-code", "общая-система")?.model).toBe("gpt-5.6-sol");
    expect(verifierFor("codex", "правки-владельца")?.model).toBe("claude-sonnet-5");
    expect(verifierFor("codex", "диагностика")?.model).toBe("claude-opus-5[1m]");
  });

  it("класс доезжает до решения, а не теряется по дороге", () => {
    const дешёвый = classifyTask({
      prompt: "собери презентацию для клиента",
      parentProvider: "claude-code",
    });
    expect(дешёвый.model).toBe("gpt-5.6-sol");
    const дорогой = classifyTask({
      prompt: "посчитай сумму возврата по гарантии",
      parentProvider: "claude-code",
    });
    expect(дорогой.model).toBe("gpt-6-astra");
  });

  it("незнакомый провайдер без проверки не остаётся", () => {
    // 09.09.2026: в bb зарегистрированы claude-code, codex, pi и acp-cursor,
    // а пара знала два. Для остальных проверяющий не назначался, то есть тред
    // на новом провайдере молча оставался без второго мозга.
    const решение = classifyTask({
      prompt: "посчитай сумму договора",
      parentProvider: "pi",
    });
    expect(решение.pair).toBe(true);
    expect(решение.provider).toBe("claude-code");
  });

  it("семейство считается по модели, а не по оболочке", () => {
    // Cursor и Pi это оболочки: за ними стоит любая модель. Тред на Cursor с
    // моделью Claude обязан проверяться моделью OpenAI, иначе выходит
    // однородная пара, которая усиливает общую ошибку вместо того, чтобы её
    // ловить.
    expect(семействоМодели("claude-opus-5[1m]")).toBe("anthropic");
    expect(семействоМодели("gpt-6-astra")).toBe("openai");
    expect(семействоМодели("gemini-3.1-pro")).toBe("google");
    expect(семействоМодели("grok-4.6")).toBe("xai");
    expect(семействоМодели("composer-2.5")).toBe("иное");

    expect(verifierFor("acp-cursor", "диагностика", "claude-sonnet-5")?.provider).toBe("codex");
    expect(verifierFor("acp-cursor", "диагностика", "gemini-3.1-pro")?.provider).toBe("claude-code");
    expect(verifierFor("pi", "диагностика", "gpt-6-astra")?.provider).toBe("claude-code");
  });


  it("длинная задача со словом «покажи» рутиной не считается", () => {
    const решение = classifyTask({
      prompt:
        "покажи, как устроен расчёт возврата по гарантии, и проверь, совпадает ли он с договором клиента, потому что в отчёте стоит другая сумма и её уже видел собственник",
      parentProvider: "claude-code",
    });
    expect(решение.pair).toBe(true);
  });

  it("откат чужой работы это необратимое, даже без слова «удали»", () => {
    // Найдено на живом треде 07.09.2026: «убери свою работу и при этом моё
    // ничего не тронь» классифицировалось рутиной. Цена ошибки здесь та же,
    // что у удаления: рядом лежит работа человека.
    for (const запрос of [
      "опять не получилось. убери свою работу и при этом мое ничего не тронь",
      "откати изменения",
      "верни как было",
    ]) {
      const решение = classifyTask({ prompt: запрос, parentProvider: "claude-code" });
      expect(решение.pair, запрос).toBe(true);
      expect(решение.taskClass, запрос).toBe("необратимое");
    }
  });

  it("«убери отступ» это вёрстка, а не откат", () => {
    for (const запрос of ["убери отступ сверху", "убери лишний пробел в заголовке"]) {
      expect(classifyTask({ prompt: запрос, parentProvider: "claude-code" }).pair, запрос).toBe(false);
    }
  });

  it("приёмка это дорогой класс: ложное «всё работает» стоит дороже всего", () => {
    // Артём дважды ловил на этом: «ты говорил что апдейт появился, а он не
    // появился». Проверку собственной работы обязан смотреть кто-то другой.
    for (const запрос of [
      "проверь все ли мои задачи по апдейту системы выполнены и работают",
      "проверь, всё ли работает",
      "все ли блоки выполнены",
    ]) {
      expect(classifyTask({ prompt: запрос, parentProvider: "claude-code" }).pair, запрос).toBe(true);
    }
  });

  it("обычное «проверь что-то» приёмкой не становится", () => {
    for (const запрос of ["проверь статус сервера", "проверь почту", "покажи список тредов"]) {
      expect(classifyTask({ prompt: запрос, parentProvider: "claude-code" }).pair, запрос).toBe(false);
    }
  });

  it("«объясни правила» в учебной задаче системной правкой не считается", () => {
    // Живой случай 10.09.2026: домашка по английскому («переведи и объясни
    // правила») попала в класс «общая-система» и получила проверку. Голое
    // слово «правил» ловит и грамматику, и правила игры.
    for (const запрос of [
      "Complete the text with the correct form of the verb in brackets. переведи и объясни правила",
      "объясни правила игры в шахматы",
    ]) {
      expect(classifyTask({ prompt: запрос, parentProvider: "codex" }).pair, запрос).toBe(false);
    }
  });

  it("постановка правила по-прежнему ловится", () => {
    for (const запрос of [
      "запиши правило, чтобы это не повторялось",
      "поменяй правила работы с клиентом",
      "заведи регламент сдачи блока",
      "сделай системный фикс правила выката",
    ]) {
      const решение = classifyTask({ prompt: запрос, parentProvider: "claude-code" });
      expect(решение.pair, запрос).toBe(true);
      expect(решение.taskClass, запрос).toBe("общая-система");
    }
  });

  it("видит правку, которая касается всей системы", () => {
    // Найдено приёмкой 07.09.2026 на живом треде: Артём просил, чтобы второй
    // мозг работал «со всеми тредами» и «на всю мою систему», а классификатор
    // отнёс это к рутине и промолчал. Универсальный квантор рядом с объектом
    // системы это и есть признак правки, которая подействует на всё.
    for (const запрос of [
      "хочу чтобы это работало со всеми тредами, на всю мою систему",
      "сделай так во всех проектах",
      "во всех тредах должно работать одинаково",
    ]) {
      const решение = classifyTask({ prompt: запрос, parentProvider: "claude-code" });
      expect(решение.pair, запрос).toBe(true);
      expect(решение.taskClass, запрос).toBe("общая-система");
    }
  });

  it("бытовое «всем» системной правкой не считается", () => {
    expect(classifyTask({ prompt: "свари всем кофе", parentProvider: "claude-code" }).pair).toBe(false);
  });

  it("не путает бытовое слово с действием над системой", () => {
    // Найдено сухим прогоном по живой базе 07.09.2026: «Картофель 1,3 кг
    // очистить» уходило в класс «необратимое» на xhigh, а «Соберись и работай
    // аккуратнее» — в «сдачу артефакта». Оба ложных срабатывания тратили бы
    // дорогой слот бюджета.
    for (const запрос of [
      '"Картофель 1,3 кг очистить" даже я вижу, что не будет на выходе 1,25 кг',
      "В чем дело? Соберись и работай всегда профессиональнее и аккуратнее",
    ]) {
      expect(classifyTask({ prompt: запрос, parentProvider: "claude-code" }).pair, запрос).toBe(false);
    }
  });

  it("настоящее действие над системой по-прежнему ловится", () => {
    for (const [запрос, класс] of [
      ["очисти базу от старых записей", "необратимое"],
      ["задеплой на прод", "необратимое"],
      ["удали папку с архивом", "необратимое"],
    ] as const) {
      const решение = classifyTask({ prompt: запрос, parentProvider: "claude-code" });
      expect(решение.pair, запрос).toBe(true);
      expect(решение.taskClass, запрос).toBe(класс);
    }
  });

  it("признаки с границей слова работают в кириллице", () => {
    // \b опирается на ASCII-класс \w, поэтому «пост\b» и «прод\b» не
    // находили НИЧЕГО: правила молча не срабатывали, и это читалось как
    // «признак не встретился».
    expect(classifyTask({ prompt: "выложи пост в канал", parentProvider: "claude-code" }).taskClass).toBe("сдача-артефакта");
    expect(classifyTask({ prompt: "выкати на прод", parentProvider: "claude-code" }).taskClass).toBe("необратимое");
  });

  it("правка общей системы идёт с меньшей мощностью и одним раундом", () => {
    const решение = classifyTask({
      prompt: "сделай системный фикс правила выката, чтобы это не повторялось",
      parentProvider: "claude-code",
    });
    expect(решение.pair).toBe(true);
    expect(решение.taskClass).toBe("общая-система");
    expect(решение.maxRounds).toBe(1);
  });
});

describe("момент запуска проверки", () => {
  it("необратимое проверяется параллельно с работой", () => {
    // Иначе находка приходит, когда удаление уже случилось.
    expect(проверятьРано("необратимое")).toBe(true);
  });

  it("остальное ждёт готового результата", () => {
    // Зеркальная беда: на сдаче артефакта параллельный проверяющий смотрит
    // рабочую папку до того, как автор что-то сделал, и проверяет пустоту.
    for (const класс of [
      "сдача-артефакта",
      "деньги-и-обещания",
      "общая-система",
      "правки-владельца",
      "диагностика",
    ] as const) {
      expect(проверятьРано(класс), класс).toBe(false);
    }
  });
});

describe("необратимое проверяется дважды", () => {
  it("рано — чтобы успеть предупредить, после — чтобы увидеть итог", () => {
    // Ранний проверяющий смотрит рабочую папку ДО действия, поэтому его
    // «расхождений не нашёл» ничего не говорит о том, что получилось.
    expect(запускатьВМомент("необратимое", "рано")).toBe(true);
    expect(запускатьВМомент("необратимое", "после")).toBe(true);
  });

  it("остальные классы проверяются только по результату", () => {
    for (const класс of ["сдача-артефакта", "деньги-и-обещания", "диагностика"] as const) {
      expect(запускатьВМомент(класс, "рано"), класс).toBe(false);
      expect(запускатьВМомент(класс, "после"), класс).toBe(true);
    }
  });
});
