/**
 * Разбор запросов ЧЕЛОВЕКА в ленте треда.
 *
 * Живёт отдельным модулем, потому что этим же разбором пользуется сухой прогон
 * по живой базе (_check/dry-run.mjs). Держать копию в прогоне нельзя: измеритель
 * разойдётся с измеряемым и покажет не то, что случится на самом деле.
 */

export interface РядЛенты {
  kind?: string;
  role?: string;
  text?: string;
  /** Кто на самом деле прислал строку: человек, агент или система. */
  initiator?: string;
  /** Не null, если строку прислал другой тред (spawn, steer, плагин). */
  senderThreadId?: string | null;
  children?: РядЛенты[] | null;
}

/**
 * Запросы ЧЕЛОВЕКА в треде, по порядку.
 *
 * Проверять `role === "user"` недостаточно, и это опасно вдвойне. Такую роль
 * несут ещё и сообщения, присланные другими тредами (spawn, steer) и плагинами
 * — включая сводку, которую в родителя шлёт этот же плагин. Считай их
 * запросами человека, и получится петля: сводка порождает новую проверку,
 * та возвращает новую сводку, и так до конца суточного бюджета.
 * Человека опознаём по трём признакам сразу.
 */
/**
 * Начало сводки второго мозга. Проверено на живой ленте 07.09.2026: сводка,
 * отправленная плагином через threads.send, приходит с initiator "user" и
 * пустым senderThreadId, то есть от сообщения человека НЕОТЛИЧИМА по служебным
 * полям. Единственный надёжный признак — наш собственный заголовок, который мы
 * же и ставим. Без этого отсева выходит петля: сводка читается как новая
 * задача, порождает проверку, та возвращает новую сводку.
 */
export const МАРКЕР_СВОДКИ = "**Второй мозг";

export function запросыЧеловека(rows: readonly РядЛенты[]): string[] {
  const найденные: string[] = [];
  const обойти = (ряд: РядЛенты): void => {
    if (ряд.kind === "conversation" && ряд.role === "user") {
      const свой = ряд.initiator === undefined || ряд.initiator === "user";
      const ничей = ряд.senderThreadId == null;
      const текст = (ряд.text ?? "").trim();
      const наша = текст.startsWith(МАРКЕР_СВОДКИ);
      if (свой && ничей && !наша && текст.length > 0) найденные.push(текст);
    }
    if (ряд.children != null) {
      for (const ребёнок of ряд.children) обойти(ребёнок);
    }
  };
  for (const ряд of rows) обойти(ряд);
  return найденные;
}

/**
 * Последний запрос человека: по нему судим о задаче.
 *
 * Раньше брался ПЕРВЫЙ, и для нового треда это одно и то же. Но у Артёма
 * десятки тредов, живущих неделями: первый запрос там про то, с чего всё
 * начиналось месяц назад, а работа давно ушла в другую сторону. Класс задачи
 * определяется тем, что человек просит СЕЙЧАС.
 */
/**
 * Отсылка к уже поставленной задаче, а не новая задача.
 *
 * Найдено пробником на живом треде 07.09.2026: последним запросом человека там
 * стояло «продолжай работу», и класс выходил «рутина», хотя работа шла дорогая.
 * Артём так пишет постоянно: «делай», «продолжай», «дальше», «ок». Судить по
 * такой строке значит судить не о задаче.
 */
const ОТСЫЛКА =
  /^\s*(?:да|ок|окей|хорошо|давай|делай|продолжай?|дальше|дожимай|доделай|работай|верно|согласен|поехали|ага|угу|плюс|go)(?![\p{L}])[\s\p{P}]*(?:работу|дальше|давай|пожалуйста)?[\s\p{P}]*$/iu;

export function значимыйЗапрос(запросы: readonly string[]): string | undefined {
  for (let и = запросы.length - 1; и >= 0; и -= 1) {
    const запрос = запросы[и];
    if (запрос.length > 60 || !ОТСЫЛКА.test(запрос)) return запрос;
  }
  return запросы.length > 0 ? запросы[запросы.length - 1] : undefined;
}

/** Последний СОДЕРЖАТЕЛЬНЫЙ запрос человека: по нему судим о задаче. */
export function последнийЗапрос(rows: readonly РядЛенты[]): string | undefined {
  return значимыйЗапрос(запросыЧеловека(rows));
}


/**
 * Отпечаток проверенной задачи.
 *
 * Раньше метка хранила ЧИСЛО запросов человека, и это оказалось хрупким:
 * стоило уточнить правило подсчёта (07.09.2026 добавился отсев чужих
 * сообщений), как сохранённое «13» стало больше нового «12», и тред закрылся
 * для второго мозга навсегда — условие «уже проверено» выполнялось всегда.
 * Отпечаток самой задачи от логики подсчёта не зависит.
 */
export function отпечатокЗадачи(задача: string): string {
  const текст = задача.trim();
  let хэш = 5381;
  for (let и = 0; и < текст.length; и += 1) {
    хэш = ((хэш << 5) + хэш + текст.charCodeAt(и)) | 0;
  }
  return `${текст.length}:${(хэш >>> 0).toString(36)}`;
}
