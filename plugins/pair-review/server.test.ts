describe("журнал решений", () => {
  const запись = (n: number) => ({
    at: n,
    threadId: `thr_${n}`,
    title: "задача",
    taskClass: "диагностика",
    решение: "проверка" as const,
    why: "почему",
  });

  it("хранит последние записи и не растёт бесконечно", () => {
    // Журнал нужен, чтобы работа второго мозга была видима человеку, а не
    // только в логе сервера. Но хранилище плагина не свалка: держим окно.
    let журнал = дописатьВЖурнал(undefined, запись(1), 3);
    for (const n of [2, 3, 4, 5]) журнал = дописатьВЖурнал(журнал, запись(n), 3);
    expect(журнал).toHaveLength(3);
    expect(журнал.map((з) => з.at)).toEqual([3, 4, 5]);
  });

  it("первая запись ложится в пустой журнал", () => {
    expect(дописатьВЖурнал(undefined, запись(1))).toHaveLength(1);
  });
});

describe("отсылка к уже поставленной задаче", () => {
  it("«продолжай работу» не считается новой задачей", () => {
    // Найдено пробником на живом треде: класс выходил «рутина», хотя работа
    // шла дорогая. Артём так пишет постоянно.
    const запросы = ["посчитай возврат по гарантии клиенту", "продолжай работу"];
    expect(значимыйЗапрос(запросы)).toBe("посчитай возврат по гарантии клиенту");
  });

  it("пропускает подряд идущие отсылки", () => {
    expect(значимыйЗапрос(["разберись почему упал прод", "да", "делай", "продолжай"]))
      .toBe("разберись почему упал прод");
  });

  it("длинное сообщение отсылкой не считается, даже если начинается с «делай»", () => {
    const длинное =
      "делай так: сначала подними снимок, потом сверь суммы в смете с договором клиента";
    expect(значимыйЗапрос(["старое", длинное])).toBe(длинное);
  });

  it("путь от ЛЕНТЫ до задачи тоже пропускает отсылку", () => {
    // Проверять значимыйЗапрос отдельно мало: 07.09.2026 слом последнегоЗапроса
    // не уронил ни одного теста, потому что путь от ленты до решения покрыт
    // не был. Замок обязан стоять там, где ходит плагин.
    const rows = [
      {
        kind: "conversation",
        role: "user",
        text: "посчитай сумму возврата по гарантии клиенту",
        initiator: "user",
        senderThreadId: null,
      },
      { kind: "conversation", role: "assistant", text: "считаю" },
      {
        kind: "conversation",
        role: "user",
        text: "продолжай",
        initiator: "user",
        senderThreadId: null,
      },
    ];
    expect(последнийЗапрос(rows)).toBe("посчитай сумму возврата по гарантии клиенту");
  });

  it("когда человек не писал ничего кроме отсылок, берём последнюю", () => {
    expect(значимыйЗапрос(["ок", "давай"])).toBe("давай");
    expect(значимыйЗапрос([])).toBeUndefined();
  });
});

describe("отметка о проверенной задаче", () => {
  it("одна и та же задача даёт один отпечаток, разные — разные", () => {
    expect(отпечатокЗадачи("посчитай возврат")).toBe(отпечатокЗадачи(" посчитай возврат "));
    expect(отпечатокЗадачи("посчитай возврат")).not.toBe(отпечатокЗадачи("посчитай возвраты"));
  });

  it("не зависит от правил подсчёта запросов", () => {
    // Прежняя метка хранила ЧИСЛО запросов человека. Стоило уточнить, кого
    // считать человеком, как сохранённое «13» стало больше нового «12», и тред
    // закрылся для второго мозга навсегда: условие «уже проверено» выполнялось
    // при любом новом запросе. Найдено пробником на живом треде 07.09.2026.
    const задача = "разберись, почему приёмка молчит";
    const было = отпечатокЗадачи(задача);
    const стало = отпечатокЗадачи(задача);
    expect(стало).toBe(было);
  });
});
