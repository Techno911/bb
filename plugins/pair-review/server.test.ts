describe("покрытие идёт за человеком, а не за деревом", () => {
  it("корневой тред покрыт с первого же запроса", () => {
    expect(человекВедёт(["задача"], false)).toBe(true);
    expect(человекВедёт([], false)).toBe(false);
  });

  it("вложенный тред покрыт, когда человек написал в него сам", () => {
    // 08.09.2026 наведение порядка в сайдбаре перенесло одиннадцать рабочих
    // тредов под генеральные, они стали дочерними, и второй мозг на них молча
    // выключился. Место в дереве это организация, а не смысл.
    expect(человекВедёт(["задание при создании", "а теперь посчитай возврат"], true)).toBe(true);
  });

  it("делегированный и проверяющий тред остаются в стороне", () => {
    // У них ровно один запрос: задание, полученное при создании. Ставить на
    // такую работу ещё одного проверяющего значит удваивать расход.
    expect(человекВедёт(["задание от агента"], true)).toBe(false);
    expect(человекВедёт([], true)).toBe(false);
  });
});

describe("сорванная проверка не крутит цикл", () => {
  const отпечаток = "131:151pt5x";

  it("после двух срывов задача больше не берётся", () => {
    // 10.09.2026: у провайдера истёк вход, проверяющие падали мгновенно, а
    // возврат слота бюджета открывал дорогу следующему запуску. За две минуты
    // на треде «Английский Home Work» родилось четырнадцать дочерних тредов,
    // все упавшие.
    expect(нуженРазбор({ задача: отпечаток, правила: 2, попыток: 0 }, отпечаток, 2)).toBe(false);
    expect(нуженРазбор({ задача: отпечаток, правила: 1, попыток: 1 }, отпечаток, 2)).toBe(true);
    expect(нуженРазбор({ задача: отпечаток, правила: 1, попыток: 2 }, отпечаток, 2)).toBe(false);
    expect(нуженРазбор({ задача: отпечаток, правила: 1, попыток: 9 }, отпечаток, 2)).toBe(false);
  });

  it("новая задача срывами прошлой не блокируется", () => {
    expect(нуженРазбор({ задача: "другая", попыток: 9 }, отпечаток, 2)).toBe(true);
  });
});
