describe("суточный бюджет проверок", () => {
  const день = Date.UTC(2026, 8, 7, 12);

  it("пускает, пока предел не выбран", () => {
    expect(бюджетПозволяет(undefined, день)).toBe(true);
    expect(бюджетПозволяет({ day: "2026-09-07", used: 5 }, день)).toBe(true);
  });

  it("останавливает на пределе: лимит подписки надо тратить на дорогое", () => {
    expect(бюджетПозволяет({ day: "2026-09-07", used: 6 }, день)).toBe(false);
    expect(бюджетПозволяет({ day: "2026-09-07", used: 9 }, день)).toBe(false);
  });

  it("держит половину запаса для дорогих классов", () => {
    // Двести тредов работают весь день. Без резерва первые же шесть задач
    // любого класса выберут бюджет к обеду, и когда придёт расчёт денег
    // клиента, проверять будет нечем.
    const выбрано = { day: "2026-09-07", used: 3 };
    expect(бюджетПозволяет(выбрано, день, 6, "сдача-артефакта")).toBe(false);
    expect(бюджетПозволяет(выбрано, день, 6, "общая-система")).toBe(false);
    expect(бюджетПозволяет(выбрано, день, 6, "деньги-и-обещания")).toBe(true);
    expect(бюджетПозволяет(выбрано, день, 6, "необратимое")).toBe(true);
    expect(бюджетПозволяет(выбрано, день, 6, "диагностика")).toBe(true);
  });

  it("дорогой класс тоже не бесконечен", () => {
    expect(бюджетПозволяет({ day: "2026-09-07", used: 6 }, день, 6, "деньги-и-обещания")).toBe(false);
  });

  it("новый день обнуляет счёт", () => {
    expect(бюджетПозволяет({ day: "2026-09-06", used: 99 }, день)).toBe(true);
    expect(следующийБюджет({ day: "2026-09-06", used: 99 }, день)).toEqual({
      day: "2026-09-07",
      used: 1,
    });
  });

  it("считает расход в пределах дня", () => {
    expect(следующийБюджет({ day: "2026-09-07", used: 2 }, день)).toEqual({
      day: "2026-09-07",
      used: 3,
    });
  });

  it("не состоявшаяся проверка бюджета не тратит", () => {
    // Иначе кончившийся лимит проверяющего выключает второй мозг на сутки
    // ровно перед тем, как лимит восстановится.
    expect(вернутьБюджет({ day: "2026-09-07", used: 3 }, день)).toEqual({
      day: "2026-09-07",
      used: 2,
    });
  });

  it("возврат не уводит счёт ниже нуля и не трогает чужой день", () => {
    expect(вернутьБюджет({ day: "2026-09-07", used: 0 }, день)).toEqual({
      day: "2026-09-07",
      used: 0,
    });
    expect(вернутьБюджет({ day: "2026-09-06", used: 5 }, день)).toEqual({
      day: "2026-09-06",
      used: 5,
    });
    expect(вернутьБюджет(undefined, день)).toBeUndefined();
  });

  it("шесть падений подряд не выключают второй мозг", () => {
    let бюджет = { day: "2026-09-07", used: 0 };
    for (let i = 0; i < 6; i += 1) {
      expect(бюджетПозволяет(бюджет, день)).toBe(true);
      бюджет = следующийБюджет(бюджет, день);
      бюджет = вернутьБюджет(бюджет, день) as typeof бюджет;
    }
    expect(бюджетПозволяет(бюджет, день)).toBe(true);
    expect(бюджет.used).toBe(0);
  });
});

describe("запросы человека в ленте", () => {
  it("берёт последний запрос человека, а не первый и не ответ модели", () => {
    // Тредам Артёма недели: первый запрос там про то, с чего всё начиналось,
    // а класс задачи задаёт то, что он просит сейчас.
    const rows = [
      {
        kind: "turn",
        children: [
          { kind: "conversation", role: "assistant", text: "сначала ответ" },
          { kind: "conversation", role: "user", text: "почини сборку" },
        ],
      },
      { kind: "conversation", role: "user", text: "посчитай возврат по гарантии" },
    ];
    expect(последнийЗапрос(rows)).toBe("посчитай возврат по гарантии");
    expect(запросыЧеловека(rows)).toHaveLength(2);
  });

  it("не считает человеком другой тред и плагин", () => {
    // Сводку в родителя шлёт этот же плагин, и она приходит с role user.
    // Прими её за запрос человека — получится петля: сводка порождает новую
    // проверку, та возвращает новую сводку, и так до конца бюджета.
    const rows = [
      { kind: "conversation", role: "user", text: "живой запрос", initiator: "user", senderThreadId: null },
      { kind: "conversation", role: "user", text: "Второй мозг · находки", initiator: "agent", senderThreadId: "thr_x" },
      { kind: "conversation", role: "user", text: "системное", initiator: "system", senderThreadId: null },
    ];
    expect(запросыЧеловека(rows)).toEqual(["живой запрос"]);
    expect(последнийЗапрос(rows)).toBe("живой запрос");
  });

  it("возвращает пусто, когда человек ещё ничего не написал", () => {
    expect(последнийЗапрос([{ kind: "conversation", role: "assistant", text: "х" }])).toBeUndefined();
    expect(последнийЗапрос([])).toBeUndefined();
  });
});

describe("задание проверяющему", () => {
  const задание = заданиеПроверяющему({
    задача: "посчитай возврат по гарантии",
    класс: "деньги-и-обещания",
    почему: "число уходит человеку",
    раунд: 1,
  });

  it("требует доказательство к каждой находке", () => {
    // Без этого второй мозг становится генератором шума: в ретроспективе один
    // непроверяемый слой дал 32 ложные находки из 52.
    expect(задание).toContain("доказательство");
    expect(задание).toContain("Находку без доказательства не пиши");
  });

  it("велит работать вслепую и ничего не менять", () => {
    expect(задание).toContain("ВСЛЕПУЮ");
    expect(задание).toContain("Только чтение");
  });

  it("несёт исходную задачу человека", () => {
    expect(задание).toContain("посчитай возврат по гарантии");
  });

  it("во втором раунде разбирает только спорное", () => {
    const второй = заданиеПроверяющему({
      задача: "з",
      класс: "к",
      почему: "п",
      раунд: 2,
    });
    expect(второй).toContain("только спорные пункты");
    expect(второй).not.toContain("ВСЛЕПУЮ");
  });
});

