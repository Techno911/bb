/** Сообщение автору с находками проверяющего. */
export function сводкаДляАвтора(args: {
  класс: string;
  вывод: string;
  раунд: number;
}): string {
  return [
    `**Второй мозг · ${args.класс}${args.раунд > 1 ? ` · раунд ${args.раунд}` : ""}**`,
    "",
    "Независимая проверка другой моделью, вслепую. Разбери каждую находку:",
    "подтверди с доказательством или отклони с доказательством, и скажи об этом человеку.",
    "",
    args.вывод.trim(),
  ].join("\n");
}

export default async function plugin(bb: BbPluginApi) {
  const хранилище = bb.storage.kv;

  async function записатьВЖурнал(
    threadId: string,
    задача: string,
    taskClass: string,
    решение: ЗаписьЖурнала["решение"],
    why: string,
  ): Promise<void> {
    const журнал = await хранилище.get<ЗаписьЖурнала[]>(КЛЮЧ_ЖУРНАЛА);
    await хранилище.set(
      КЛЮЧ_ЖУРНАЛА,
      дописатьВЖурнал(журнал, {
        at: Date.now(),
        threadId,
        title: задача.slice(0, 70).replace(/\s+/g, " "),
        taskClass,
        решение,
        why,
      }),
    );
  }

  async function запуститьПроверку(thread: {
    id: string;
    projectId: string | null;
    providerId: string | null;
    environmentId: string | null;
  }): Promise<void> {
    const лента = await bb.sdk.threads.timeline({
      threadId: thread.id,
      includeNestedRows: "true",
    });
    const запросы = запросыЧеловека(лента.rows as РядЛенты[]);
    if (запросы.length === 0) return;
    const задача = значимыйЗапрос(запросы);
    if (задача === undefined) return;

    // Проверка привязана к КОНКРЕТНОМУ запросу человека, а не к треду.
    // Иначе живущий неделями тред получил бы второй мозг ровно один раз за всю
    // жизнь, а дальше молчал бы навсегда — при том что работа в нём идёт
    // каждый день. И наоборот, без счётчика проверка запускалась бы после
    // каждого хода агента внутри одной и той же задачи.
    const метка = await хранилище.get<{ задача?: string }>(
      `${КЛЮЧ_ПРОВЕРКИ}parent:${thread.id}`,
    );
    const отпечаток = отпечатокЗадачи(задача);
    if (метка?.задача === отпечаток) return;

    const решение: PairDecision = classifyTask({
      prompt: задача,
      parentProvider: thread.providerId ?? "",
    });
    if (!решение.pair || решение.provider === undefined) {
      // Отметку ставим и на отказе: иначе классификатор гонялся бы заново
      // после каждого хода агента по одному и тому же запросу.
      await хранилище.set(`${КЛЮЧ_ПРОВЕРКИ}parent:${thread.id}`, {
        задача: отпечаток,
        childThreadId: null,
        at: Date.now(),
      });
      await записатьВЖурнал(thread.id, задача, решение.taskClass, "молчим", решение.why);
      bb.log.info(
        `второй мозг не нужен для ${thread.id}: ${решение.taskClass} — ${решение.why}`,
      );
      return;
    }

    const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
    if (!бюджетПозволяет(бюджет, Date.now(), БЮДЖЕТ_В_СУТКИ, решение.taskClass)) {
      // Отметку НЕ ставим: бюджет вернётся завтра, и задача этого класса
      // заслуживает проверки, а не молчаливого пропуска навсегда.
      await записатьВЖурнал(
        thread.id,
        задача,
        решение.taskClass,
        "бюджет",
        "суточный бюджет этого класса выбран, вернусь завтра",
      );
      bb.log.info(
        `второй мозг отложен для ${thread.id}: суточный бюджет для класса ${решение.taskClass} выбран`,
      );
      return;
    }

    if (thread.projectId === null) return;
    const ребёнок = await bb.sdk.threads.spawn({
      projectId: thread.projectId,
      // Та же папка, что у автора: проверяющий смотрит те же артефакты, а не
      // пустое новое рабочее дерево.
      environment:
        thread.environmentId === null
          ? { type: "project-default" }
          : { type: "reuse", environmentId: thread.environmentId },
      parentThreadId: thread.id,
      title: `Проверка · ${решение.taskClass}`,
      prompt: заданиеПроверяющему({
        задача,
        класс: решение.taskClass,
        почему: решение.why,
        раунд: 1,
      }),
      providerId: решение.provider,
      ...(решение.model === undefined ? {} : { model: решение.model }),
      ...(решение.reasoningLevel === undefined
        ? {}
        : { reasoningLevel: решение.reasoningLevel }),
    });

    await хранилище.set(КЛЮЧ_БЮДЖЕТА, следующийБюджет(бюджет));
    await хранилище.set(`${КЛЮЧ_ПРОВЕРКИ}${ребёнок.id}`, {
      parentThreadId: thread.id,
      taskClass: решение.taskClass,
      round: 1,
      maxRounds: решение.maxRounds ?? 1,
      startedAt: Date.now(),
    } satisfies Проверка);
    // Метка на родителе: этот запрос человека уже проверен. Следующий запрос
    // увеличит счёт, и второй мозг подключится снова.
    await хранилище.set(`${КЛЮЧ_ПРОВЕРКИ}parent:${thread.id}`, {
      задача: отпечаток,
      childThreadId: ребёнок.id,
      at: Date.now(),
    });
    await записатьВЖурнал(
      thread.id,
      задача,
      решение.taskClass,
      "проверка",
      `${решение.provider}/${решение.model}, ${решение.reasoningLevel}, раундов ${решение.maxRounds}`,
    );
    bb.log.info(
      `второй мозг: ${решение.provider}/${решение.model} проверяет ${thread.id} (${решение.taskClass})`,
    );
  }

  async function вернутьНаходки(threadId: string): Promise<void> {
    const проверка = await хранилище.get<Проверка>(`${КЛЮЧ_ПРОВЕРКИ}${threadId}`);
    if (проверка === undefined) return;
    await хранилище.delete(`${КЛЮЧ_ПРОВЕРКИ}${threadId}`);
    let вывод = "";
    try {
      const результат = await bb.sdk.threads.output({ threadId });
      вывод = (результат.output ?? "").trim();
    } catch (error) {
      bb.log.warn(
        `второй мозг: не прочитал вывод ${threadId}: ${
          error instanceof Error ? error.message : String(error)
        }`,
      );
      return;
    }
    if (вывод.length === 0) return;
    // Молчание проверяющего это тоже результат, но человека им не тревожим:
    // в родителя уходит только то, что требует разбора.
    if (/расхождений не нашёл/i.test(вывод) && вывод.length < 400) {
      bb.log.info(`второй мозг: ${threadId} расхождений не нашёл`);
      return;
    }
    await bb.sdk.threads.send({
      threadId: проверка.parentThreadId,
      mode: "steer-if-active",
      input: [
        {
          type: "text",
          mentions: [],
          text: сводкаДляАвтора({
            класс: проверка.taskClass,
            вывод,
            раунд: проверка.round,
          }),
        },
      ],
    });
  }

  bb.cli.register({
    name: "pair-review",
    summary: "Второй мозг: что проверено, что пропущено и почему",
    commands: [
      {
        name: "show",
        summary: "Журнал решений и остаток суточного бюджета",
        usage: "bb pair-review show [--json]",
      },
      {
        name: "probe",
        summary: "Что плагин увидит в конкретном треде: запросы человека и класс",
        usage: "bb pair-review probe <threadId>",
      },
    ],
    async run(argv) {
      const json = argv.includes("--json");
      const слова = argv.filter((арг) => !арг.startsWith("--"));
      // Пробник читает ленту ТЕМ ЖЕ способом, что и сам плагин. Разбор событий
      // базы со стороны это другой формат, и он ничего не доказывает о том,
      // что плагин увидит на живом треде.
      if (слова[0] === "probe") {
        const threadId = слова[1];
        if (threadId === undefined) {
          return { exitCode: 1, stderr: "нужен id треда: bb pair-review probe <threadId>" };
        }
        const тред = await bb.sdk.threads.get({ threadId });
        const лента = await bb.sdk.threads.timeline({
          threadId,
          includeNestedRows: "true",
        });
        const запросы = запросыЧеловека(лента.rows as РядЛенты[]);
        const метка = await хранилище.get<{ задача?: string }>(
          `${КЛЮЧ_ПРОВЕРКИ}parent:${threadId}`,
        );
        const задача = значимыйЗапрос(запросы);
        const решение =
          задача === undefined
            ? null
            : classifyTask({
                prompt: задача,
                parentProvider: тред.providerId ?? "",
              });
        const итог = {
          тред: threadId,
          провайдер: тред.providerId ?? null,
          строкЛенты: лента.rows.length,
          запросовЧеловека: запросы.length,
          этаЗадачаУжеПроверена:
            задача !== undefined && метка?.задача === отпечатокЗадачи(задача),
          последний: задача?.slice(0, 120) ?? null,
          класс: решение?.taskClass ?? null,
          подключится: решение?.pair ?? false,
          мощность: решение?.reasoningLevel ?? null,
          раундов: решение?.maxRounds ?? null,
          почему: решение?.why ?? null,
        };
        if (json) return { exitCode: 0, stdout: JSON.stringify(итог, null, 2) };
        return {
          exitCode: 0,
          stdout: [
            `Тред ${итог.тред} (${итог.провайдер ?? "провайдер неизвестен"})`,
            `Строк ленты: ${итог.строкЛенты}, запросов человека: ${итог.запросовЧеловека}, эта задача уже проверена: ${итог.этаЗадачаУжеПроверена ? "да" : "нет"}`,
            `Последний запрос: ${итог.последний ?? "человек ещё не писал"}`,
            `Класс: ${итог.класс ?? "—"}`,
            итог.подключится
              ? `Второй мозг ПОДКЛЮЧИТСЯ: ${итог.мощность}, раундов ${итог.раундов}`
              : `Второй мозг промолчит: ${итог.почему ?? "нет запроса человека"}`,
          ].join("\n"),
        };
      }
      const журнал = (await хранилище.get<ЗаписьЖурнала[]>(КЛЮЧ_ЖУРНАЛА)) ?? [];
      const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
      const сегодняшний =
        бюджет !== undefined && бюджет.day === сегодня() ? бюджет.used : 0;
      if (json) {
        return {
          exitCode: 0,
          stdout: JSON.stringify({ бюджет: сегодняшний, предел: БЮДЖЕТ_В_СУТКИ, журнал }),
        };
      }
      const строки: string[] = [
        `Бюджет на сегодня: ${сегодняшний} из ${БЮДЖЕТ_В_СУТКИ}` +
          ` (дешёвым классам доступно ${ПРЕДЕЛ_ДЕШЁВЫХ})`,
        "",
      ];
      if (журнал.length === 0) {
        строки.push("Решений пока нет: второй мозг подключается, когда человек");
        строки.push("ставит задачу дорогого класса, а не после каждого хода.");
      } else {
        for (const з of журнал.slice(-20)) {
          const время = new Date(з.at).toLocaleString("ru-RU", {
            day: "2-digit",
            month: "2-digit",
            hour: "2-digit",
            minute: "2-digit",
          });
          строки.push(`${время}  ${з.решение.padEnd(8)} ${з.taskClass}`);
          строки.push(`   «${з.title}»`);
          строки.push(`   ${з.why}`);
        }
      }
      return { exitCode: 0, stdout: строки.join("\n") };
    },
  });

  bb.events.on("thread.idle", ({ thread }) => {
    void (async () => {
      try {
        const это_проверка = await хранилище.get<Проверка>(
          `${КЛЮЧ_ПРОВЕРКИ}${thread.id}`,
        );
        if (это_проверка !== undefined) {
          await вернутьНаходки(thread.id);
          return;
        }
        if (thread.parentThreadId != null) return;
        if (thread.visibility !== "visible") return;
        await запуститьПроверку({
          id: thread.id,
          projectId: thread.projectId ?? null,
          providerId: thread.providerId ?? null,
          environmentId: thread.environmentId ?? null,
        });
      } catch (error) {
        // Сбой второго мозга не должен мешать основной работе человека.
        bb.log.warn(
          `второй мозг пропущен: ${
            error instanceof Error ? error.message : String(error)
          }`,
        );
      }
    })();
  });

  bb.events.on("thread.failed", ({ thread }) => {
    void (async () => {
      try {
        const проверка = await хранилище.get<Проверка>(
          `${КЛЮЧ_ПРОВЕРКИ}${thread.id}`,
        );
        if (проверка === undefined) return;
        await хранилище.delete(`${КЛЮЧ_ПРОВЕРКИ}${thread.id}`);
        // Метку на родителе тоже снимаем: иначе один упавший проверяющий
        // навсегда закрывает этому треду дорогу ко второму мозгу.
        await хранилище.delete(`${КЛЮЧ_ПРОВЕРКИ}parent:${проверка.parentThreadId}`);
        // Не состоявшаяся проверка бюджета не тратит, иначе кончившийся лимит
        // проверяющего выключает второй мозг на сутки вперёд.
        const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
        const возврат = вернутьБюджет(бюджет);
        if (возврат !== undefined) await хранилище.set(КЛЮЧ_БЮДЖЕТА, возврат);
        // Падение проверяющего (кончился лимит, оборвалась связь) не повод
        // дёргать человека: каждый десятый дочерний тред падает.
        bb.log.info(`второй мозг: проверка ${thread.id} не состоялась, бюджет возвращён`);
      } catch {
        /* тишина намеренно: это уже путь обработки ошибки */
      }
    })();
  });
}
