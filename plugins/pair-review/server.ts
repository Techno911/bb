/**
 * Ожидание, прерываемое сигналом остановки.
 *
 * Голый setTimeout здесь не годится: служба спит минуту и не слышит остановку,
 * поэтому при перезагрузке плагина сервер сообщает «service watch-cost did not
 * stop», а сам плагин переходит в состояние degraded (поймано 07.09.2026 сразу
 * после установки датчика).
 */
function подождать(мс: number, signal: AbortSignal): Promise<void> {
  return new Promise((готово) => {
    const таймер = setTimeout(готово, мс);
    signal.addEventListener(
      "abort",
      () => {
        clearTimeout(таймер);
        готово();
      },
      { once: true },
    );
  });
}

export default async function plugin(bb: BbPluginApi) {
  const хранилище = bb.storage.kv;

  /**
   * Единственная дверь для запуска проверяющего.
   *
   * Оба места (первый раунд и второй) идут через неё, потому что проверка
   * бюджета рядом с вызовом spawn держится только на внимательности: 07.09.2026
   * второй раунд списывал слот ПОСЛЕ запуска и предел не смотрел вовсе, так что
   * шесть двухраундовых задач поднимали двенадцать проверяющих. Здесь порядок
   * задан конструкцией: сначала предел, потом запуск, потом списание.
   */
  async function спавнитьПроверяющего(args: {
    thread: { id: string; projectId: string; environmentId: string | null };
    taskClass: string;
    задача: string;
    заголовок: string;
    задание: string;
    provider: string;
    model?: string;
    reasoningLevel?: "medium" | "high" | "xhigh";
    round: number;
    maxRounds: number;
  }): Promise<{ id: string } | null> {
    const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
    if (!бюджетПозволяет(бюджет, Date.now(), БЮДЖЕТ_В_СУТКИ, args.taskClass)) {
      await записатьВЖурнал(
        args.thread.id,
        args.задача,
        args.taskClass,
        "бюджет",
        args.round > 1
          ? `второй раунд отложен: суточный бюджет класса ${args.taskClass} выбран`
          : "суточный бюджет этого класса выбран, вернусь завтра",
      );
      return null;
    }
    const ребёнок = await bb.sdk.threads.spawn({
      projectId: args.thread.projectId,
      environment:
        args.thread.environmentId === null
          ? { type: "project-default" }
          : { type: "reuse", environmentId: args.thread.environmentId },
      parentThreadId: args.thread.id,
      title: args.заголовок,
      prompt: args.задание,
      providerId: args.provider,
      ...(args.model === undefined ? {} : { model: args.model }),
      ...(args.reasoningLevel === undefined
        ? {}
        : { reasoningLevel: args.reasoningLevel }),
    });
    await хранилище.set(КЛЮЧ_БЮДЖЕТА, следующийБюджет(бюджет));
    await хранилище.set(`${КЛЮЧ_ПРОВЕРКИ}${ребёнок.id}`, {
      parentThreadId: args.thread.id,
      taskClass: args.taskClass,
      задача: args.задача,
      round: args.round,
      maxRounds: args.maxRounds,
      startedAt: Date.now(),
    } satisfies Проверка);
    return ребёнок;
  }

  async function записатьВЖурнал(
    threadId: string,
    задача: string,
    taskClass: string,
    решение: ЗаписьЖурнала["решение"],
    why: string,
  ): Promise<void> {
    const журнал = await хранилище.get<ЗаписьЖурнала[]>(КЛЮЧ_ЖУРНАЛА);
    await хранилище.set(
      КЛЮЧ_ЖУРНАЛА,
      дописатьВЖурнал(журнал, {
        at: Date.now(),
        threadId,
        title: задача.slice(0, 70).replace(/\s+/g, " "),
        taskClass,
        решение,
        why,
      }),
    );
  }

  async function запуститьПроверку(
    thread: {
      id: string;
      projectId: string | null;
      providerId: string | null;
      environmentId: string | null;
      parentThreadId?: string | null;
      model?: string;
    },
    момент: "рано" | "после",
  ): Promise<void> {
    const лента = await bb.sdk.threads.timeline({
      threadId: thread.id,
      includeNestedRows: "true",
    });
    const запросы = запросыЧеловека(лента.rows as РядЛенты[]);
    if (!человекВедёт(запросы, thread.parentThreadId != null)) return;
    const задача = значимыйЗапрос(запросы);
    if (задача === undefined) return;

    // Проверка привязана к КОНКРЕТНОМУ запросу человека, а не к треду.
    // Иначе живущий неделями тред получил бы второй мозг ровно один раз за всю
    // жизнь, а дальше молчал бы навсегда — при том что работа в нём идёт
    // каждый день. И наоборот, без счётчика проверка запускалась бы после
    // каждого хода агента внутри одной и той же задачи.
    // Отметка своя у каждого момента: иначе ранняя проверка необратимого
    // закрывала бы дорогу поздней, и итог остался бы непроверенным.
    const ключМетки = `${КЛЮЧ_ПРОВЕРКИ}parent:${thread.id}:${момент}`;
    const метка = await хранилище.get<МеткаРодителя>(ключМетки);
    const отпечаток = отпечатокЗадачи(задача);
    if (!нуженРазбор(метка, отпечаток)) return;

    const решение: PairDecision = classifyTask({
      prompt: задача,
      parentProvider: thread.providerId ?? "",
      ...(thread.model === undefined ? {} : { parentModel: thread.model }),
    });
    if (!решение.pair || решение.provider === undefined) {
      // Отметку на отказе НЕ ставим. Классификация это регулярка, гонять её
      // заново дёшево, а сохранённый отказ переживает исправление правил: так
      // пропущенная проверка выглядела выполненной (childThreadId: null).
      await записатьВЖурнал(thread.id, задача, решение.taskClass, "молчим", решение.why);
      bb.log.info(
        `второй мозг не нужен для ${thread.id}: ${решение.taskClass} — ${решение.why}`,
      );
      return;
    }

    // Момент запуска у каждого класса свой. Необратимое проверяется ДВАЖДЫ:
    // параллельно, чтобы успеть предупредить, и по готовому результату, потому
    // что ранний проверяющий видел рабочую папку до действия и его «расхождений
    // не нашёл» об итоге не говорит ничего. Остальные классы ждут результата:
    // параллельный проверяющий на сдаче артефакта смотрел бы пустое место.
    if (!запускатьВМомент(решение.taskClass, момент)) return;

    if (thread.projectId === null) return;
    const ребёнок = await спавнитьПроверяющего({
      thread: {
        id: thread.id,
        projectId: thread.projectId,
        environmentId: thread.environmentId,
      },
      taskClass: решение.taskClass,
      задача,
      заголовок: `Проверка · ${решение.taskClass}`,
      задание: заданиеПроверяющему({
        задача,
        класс: решение.taskClass,
        почему: решение.why,
        раунд: 1,
      }),
      provider: решение.provider,
      ...(решение.model === undefined ? {} : { model: решение.model }),
      ...(решение.reasoningLevel === undefined
        ? {}
        : { reasoningLevel: решение.reasoningLevel }),
      round: 1,
      maxRounds: решение.maxRounds ?? 1,
    });
    if (ребёнок === null) return;

    await хранилище.set(ключМетки, {
      задача: отпечаток,
      правила: ВЕРСИЯ_ПРАВИЛ,
      childThreadId: ребёнок.id,
      at: Date.now(),
    });
    await записатьВЖурнал(
      thread.id,
      задача,
      решение.taskClass,
      "проверка",
      `${решение.provider}/${решение.model}, ${решение.reasoningLevel}, раундов ${решение.maxRounds}`,
    );
    bb.log.info(
      `второй мозг: ${решение.provider}/${решение.model} проверяет ${thread.id} (${решение.taskClass})`,
    );
  }

  async function вернутьНаходки(threadId: string): Promise<void> {
    const проверка = await хранилище.get<Проверка>(`${КЛЮЧ_ПРОВЕРКИ}${threadId}`);
    if (проверка === undefined) return;
    await хранилище.delete(`${КЛЮЧ_ПРОВЕРКИ}${threadId}`);
    let вывод = "";
    try {
      const результат = await bb.sdk.threads.output({ threadId });
      вывод = (результат.output ?? "").trim();
    } catch (error) {
      bb.log.warn(
        `второй мозг: не прочитал вывод ${threadId}: ${
          error instanceof Error ? error.message : String(error)
        }`,
      );
      return;
    }
    if (вывод.length === 0) return;
    // Молчание проверяющего это тоже результат, но человека им не тревожим:
    // в родителя уходит только то, что требует разбора.
    if (/расхождений не нашёл/i.test(вывод) && вывод.length < 400) {
      bb.log.info(`второй мозг: ${threadId} расхождений не нашёл`);
      return;
    }
    await bb.sdk.threads.send({
      threadId: проверка.parentThreadId,
      mode: "steer-if-active",
      input: [
        {
          type: "text",
          mentions: [],
          text: сводкаДляАвтора({
            класс: проверка.taskClass,
            вывод,
            раунд: проверка.round,
          }),
        },
      ],
    });

    // Второй раунд обещан дорогим классам, значит должен состояться. Ждём
    // ответа автора на находки: когда он закончит ход, проверяющий скажет,
    // закрыты они или нет. Без этого «раундов 2» было обещанием без механики.
    if (проверка.round < проверка.maxRounds) {
      await хранилище.set(`${КЛЮЧ_РАУНДА}${проверка.parentThreadId}`, {
        задача: проверка.задача ?? "",
        находки: вывод,
        taskClass: проверка.taskClass,
        round: проверка.round + 1,
        maxRounds: проверка.maxRounds,
        at: Date.now(),
      });
    }
  }

  /** Второй раунд: проверяющий судит, закрыты ли его собственные находки. */
  async function второйРаунд(thread: {
    id: string;
    projectId: string | null;
    providerId: string | null;
    environmentId: string | null;
  }, ответАвтора: string | null): Promise<boolean> {
    const ожидание = await хранилище.get<{
      задача: string;
      находки: string;
      taskClass: string;
      round: number;
      maxRounds: number;
    }>(`${КЛЮЧ_РАУНДА}${thread.id}`);
    if (ожидание === undefined) return false;
    await хранилище.delete(`${КЛЮЧ_РАУНДА}${thread.id}`);
    if (thread.projectId === null) return false;
    const проверяющий = verifierFor(
      thread.providerId ?? "",
      ожидание.taskClass as never,
    );
    if (проверяющий === undefined) return false;

    const ребёнок = await спавнитьПроверяющего({
      thread: {
        id: thread.id,
        projectId: thread.projectId,
        environmentId: thread.environmentId,
      },
      taskClass: ожидание.taskClass,
      задача: ожидание.задача,
      заголовок: `Проверка · ${ожидание.taskClass} · раунд ${ожидание.round}`,
      задание: заданиеПроверяющему({
        задача: ожидание.задача,
        класс: ожидание.taskClass,
        почему: "второй раунд: проверка, закрыты ли находки",
        раунд: ожидание.round,
        находки: ожидание.находки,
        ответАвтора: ответАвтора ?? "",
      }),
      provider: проверяющий.provider,
      model: проверяющий.model,
      reasoningLevel: "high",
      round: ожидание.round,
      maxRounds: ожидание.maxRounds,
    });
    if (ребёнок === null) return false;
    await записатьВЖурнал(
      thread.id,
      ожидание.задача,
      ожидание.taskClass,
      "проверка",
      `раунд ${ожидание.round}: проверяю, закрыты ли находки`,
    );
    return true;
  }

  /**
   * Порог, после которого ход считается разросшимся.
   *
   * Замер по живой базе 07.09.2026: средний ход в системе стоит 2,8 млн
   * токенов, а самый дорогой (55 млн за ОДИН ход) состоял из 270 команд и 42
   * правок без единого делегирования. Дело не в модели треда, а в том, что
   * каждый следующий вызов перечитывает разросшийся контекст. Инструкция
   * «выноси механику в дочерний тред» без датчика регрессирует к среднему,
   * поэтому напоминание приходит в тот момент, когда оно ещё что-то меняет.
   */
  const ПОРОГ_РАЗРАСТАНИЯ = 90;
  const КЛЮЧ_СОВЕТА = "advice:";

  async function присмотретьЗаРасходом(): Promise<void> {
    const идущие = await bb.sdk.threads.listRunning({});
    for (const краткий of идущие) {
      const тред = await bb.sdk.threads.get({ threadId: краткий.id });
      try {
        const лента = await bb.sdk.threads.timeline({
          threadId: тред.id,
          includeNestedRows: "true",
        });
        const запросы = запросыЧеловека(лента.rows as РядЛенты[]);
        if (!человекВедёт(запросы, тред.parentThreadId != null)) continue;
        const задача = значимыйЗапрос(запросы);
        if (задача === undefined) continue;
        const отпечаток = отпечатокЗадачи(задача);
        const уже = await хранилище.get<{ задача?: string }>(
          `${КЛЮЧ_СОВЕТА}${тред.id}`,
        );
        if (уже?.задача === отпечаток) continue;

        const работа = шаговПослеЗапроса(лента.rows as РядЛенты[]);
        if (работа < ПОРОГ_РАЗРАСТАНИЯ) continue;

        await хранилище.set(`${КЛЮЧ_СОВЕТА}${тред.id}`, {
          задача: отпечаток,
          at: Date.now(),
        });
        await bb.sdk.threads.send({
          threadId: тред.id,
          mode: "steer-if-active",
          input: [
            {
              type: "text",
              mentions: [],
              text: [
                `**Расход · ${работа} рабочих шагов в этой задаче**`,
                "",
                "Каждый следующий ход перечитывает весь накопленный контекст, поэтому",
                "длинная механическая серия здесь стоит дороже всего остального.",
                "Если впереди ещё перебор, сбор или однотипные правки, вынеси их в дочерний",
                "тред на дешёвой модели и верни сюда итог, а не сырые выводы:",
                "",
                "`bb thread spawn --provider claude-code --model claude-sonnet-5 --prompt \"...\"`",
                "",
                "Решения, суждение о качестве и текст для человека оставь себе.",
              ].join("\n"),
            },
          ],
        });
        bb.log.info(`расход: подсказал вынести механику в ${тред.id} (${работа} шагов)`);
      } catch (error) {
        bb.log.warn(
          `присмотр за расходом пропущен для ${тред.id}: ${
            error instanceof Error ? error.message : String(error)
          }`,
        );
      }
    }
  }

  bb.background.service("watch-cost", {
    async start(signal) {
      while (!signal.aborted) {
        try {
          await присмотретьЗаРасходом();
        } catch (error) {
          bb.log.warn(
            `присмотр за расходом сорвался: ${
              error instanceof Error ? error.message : String(error)
            }`,
          );
        }
        await подождать(60_000, signal);
      }
    },
  });

  bb.cli.register({
    name: "pair-review",
    summary: "Второй мозг: что проверено, что пропущено и почему",
    commands: [
      {
        name: "show",
        summary: "Журнал решений и остаток суточного бюджета",
        usage: "bb pair-review show [--json]",
      },
      {
        name: "probe",
        summary: "Что плагин увидит в конкретном треде: запросы человека и класс",
        usage: "bb pair-review probe <threadId>",
      },
      {
        name: "budget",
        summary: "Показать или поправить израсходованный за сегодня бюджет",
        usage: "bb pair-review budget [число]",
      },
    ],
    async run(argv) {
      const json = argv.includes("--json");
      const слова = argv.filter((арг) => !арг.startsWith("--"));
      // Пробник читает ленту ТЕМ ЖЕ способом, что и сам плагин. Разбор событий
      // базы со стороны это другой формат, и он ничего не доказывает о том,
      // что плагин увидит на живом треде.
      // Правка расхода нужна, когда слоты потрачены на то, что работой
      // человека не является: 09.09.2026 сторож по расписанию выбрал весь
      // дневной бюджет, и настоящая задача осталась без проверки.
      if (слова[0] === "budget") {
        const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
        const текущий =
          бюджет !== undefined && бюджет.day === сегодня() ? бюджет.used : 0;
        if (слова[1] === undefined) {
          return {
            exitCode: 0,
            stdout: `Израсходовано сегодня: ${текущий} из ${БЮДЖЕТ_В_СУТКИ}`,
          };
        }
        const новое = Number.parseInt(слова[1], 10);
        if (!Number.isFinite(новое) || новое < 0 || новое > БЮДЖЕТ_В_СУТКИ) {
          return {
            exitCode: 1,
            stderr: `нужно целое число от 0 до ${БЮДЖЕТ_В_СУТКИ}`,
          };
        }
        await хранилище.set(КЛЮЧ_БЮДЖЕТА, { day: сегодня(), used: новое });
        return {
          exitCode: 0,
          stdout: `Израсходовано сегодня: было ${текущий}, стало ${новое} из ${БЮДЖЕТ_В_СУТКИ}`,
        };
      }

      if (слова[0] === "probe") {
        const threadId = слова[1];
        if (threadId === undefined) {
          return { exitCode: 1, stderr: "нужен id треда: bb pair-review probe <threadId>" };
        }
        const тред = await bb.sdk.threads.get({ threadId });
        const лента = await bb.sdk.threads.timeline({
          threadId,
          includeNestedRows: "true",
        });
        const запросы = запросыЧеловека(лента.rows as РядЛенты[]);
        const метка =
          (await хранилище.get<МеткаРодителя>(`${КЛЮЧ_ПРОВЕРКИ}parent:${threadId}:после`)) ??
          (await хранилище.get<МеткаРодителя>(`${КЛЮЧ_ПРОВЕРКИ}parent:${threadId}:рано`));
        const задача = значимыйЗапрос(запросы);
        const решение =
          задача === undefined
            ? null
            : classifyTask({
                prompt: задача,
                parentProvider: тред.providerId ?? "",
              });
        // Состав ленты: по нему видно, из чего состоит работа в треде и
        // сколько её ушло на механику, которую можно было отдать дешёвой модели.
        const состав: Record<string, number> = {};
        const обойтиСостав = (ряд: РядЛенты & { children?: unknown }): void => {
          const вид = ряд.kind ?? "?";
          состав[вид] = (состав[вид] ?? 0) + 1;
          const дети = (ряд as { children?: РядЛенты[] | null }).children;
          if (дети != null) for (const р of дети) обойтиСостав(р);
        };
        for (const ряд of лента.rows as РядЛенты[]) обойтиСостав(ряд);

        // Пробник обязан судить теми же функциями, что и плагин: своя копия
        // условия трижды за сессию показывала не то, что произойдёт на деле.
        const ведёт = человекВедёт(запросы, тред.parentThreadId != null);
        const итог = {
          тред: threadId,
          вложенный: тред.parentThreadId != null,
          ведётЧеловек: ведёт,
          состав,
          провайдер: тред.providerId ?? null,
          строкЛенты: лента.rows.length,
          запросовЧеловека: запросы.length,
          этаЗадачаУжеПроверена:
            задача !== undefined &&
            !нуженРазбор(метка, отпечатокЗадачи(задача)),
          последний: задача?.slice(0, 120) ?? null,
          класс: решение?.taskClass ?? null,
          подключится: решение?.pair ?? false,
          мощность: решение?.reasoningLevel ?? null,
          раундов: решение?.maxRounds ?? null,
          почему: решение?.why ?? null,
        };
        if (json) return { exitCode: 0, stdout: JSON.stringify(итог, null, 2) };
        return {
          exitCode: 0,
          stdout: [
            `Тред ${итог.тред} (${итог.провайдер ?? "провайдер неизвестен"})`,
            `Строк ленты: ${итог.строкЛенты}, запросов человека: ${итог.запросовЧеловека}, эта задача уже проверена: ${итог.этаЗадачаУжеПроверена ? "да" : "нет"}`,
            `Состав ленты: ${Object.entries(итог.состав)
              .sort((a, b) => b[1] - a[1])
              .map(([к, н]) => `${к} ${н}`)
              .join(", ")}`,
            `Последний запрос: ${итог.последний ?? "человек ещё не писал"}`,
            `Класс: ${итог.класс ?? "—"}`,
            !итог.ведётЧеловек
              ? `Второй мозг не берётся: ${
                  итог.вложенный
                    ? "вложенный тред, человек в него сам не писал (задание при создании не в счёт)"
                    : "человек ещё ничего не написал"
                }`
              : итог.подключится
                ? `Второй мозг ПОДКЛЮЧИТСЯ: ${итог.мощность}, раундов ${итог.раундов}`
                : `Второй мозг промолчит: ${итог.почему ?? "нет запроса человека"}`,
          ].join("\n"),
        };
      }
      const журнал = (await хранилище.get<ЗаписьЖурнала[]>(КЛЮЧ_ЖУРНАЛА)) ?? [];
      const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
      const сегодняшний =
        бюджет !== undefined && бюджет.day === сегодня() ? бюджет.used : 0;
      if (json) {
        return {
          exitCode: 0,
          stdout: JSON.stringify({ бюджет: сегодняшний, предел: БЮДЖЕТ_В_СУТКИ, журнал }),
        };
      }
      const строки: string[] = [
        `Бюджет на сегодня: ${сегодняшний} из ${БЮДЖЕТ_В_СУТКИ}` +
          ` (дешёвым классам доступно ${ПРЕДЕЛ_ДЕШЁВЫХ})`,
        "",
      ];
      if (журнал.length === 0) {
        строки.push("Решений пока нет: второй мозг подключается, когда человек");
        строки.push("ставит задачу дорогого класса, а не после каждого хода.");
      } else {
        for (const з of журнал.slice(-20)) {
          const время = new Date(з.at).toLocaleString("ru-RU", {
            day: "2-digit",
            month: "2-digit",
            hour: "2-digit",
            minute: "2-digit",
          });
          строки.push(`${время}  ${з.решение.padEnd(8)} ${з.taskClass}`);
          строки.push(`   «${з.title}»`);
          строки.push(`   ${з.why}`);
        }
      }
      return { exitCode: 0, stdout: строки.join("\n") };
    },
  });

  /**
   * Проверка стартует ВМЕСТЕ с работой автора, а не после неё.
   *
   * Найдено проверяющим 07.09.2026: на `thread.idle` находки приходят, когда
   * удаление или отправка клиенту уже состоялись. Проверяющий работает вслепую
   * и вывод автора ему не нужен, поэтому его можно запускать сразу. Полной
   * гарантии это не даёт — плагин не гейт разрешений и автора не останавливает,
   * — но окно сокращается с «после хода» до «параллельно с ходом».
   *
   * Подписка двойная: `thread.active` это быстрый путь, `thread.idle` остаётся
   * страховкой на случай, когда в момент старта запрос ещё не попал в ленту.
   * Двойного запуска не будет: отметка о разобранной задаче общая.
   */
  const наПереходе = (thread: {
    id: string;
    parentThreadId?: string | null;
    visibility?: string;
    projectId?: string | null;
    providerId?: string | null;
    environmentId?: string | null;
  }): void => {
    void (async () => {
      try {
        if (thread.visibility !== "visible") return;
        await запуститьПроверку(
          {
            id: thread.id,
            projectId: thread.projectId ?? null,
            providerId: thread.providerId ?? null,
            environmentId: thread.environmentId ?? null,
            parentThreadId: thread.parentThreadId ?? null,
          },
          "рано",
        );
      } catch (error) {
        bb.log.warn(
          `второй мозг пропущен: ${
            error instanceof Error ? error.message : String(error)
          }`,
        );
      }
    })();
  };

  bb.events.on("thread.active", ({ thread }) => {
    наПереходе(thread);
  });

  bb.events.on("thread.idle", ({ thread, lastAssistantText }) => {
    void (async () => {
      try {
        const это_проверка = await хранилище.get<Проверка>(
          `${КЛЮЧ_ПРОВЕРКИ}${thread.id}`,
        );
        if (это_проверка !== undefined) {
          await вернутьНаходки(thread.id);
          return;
        }
        // Автор ответил на находки: пора сказать, закрыты они или нет.
        if (thread.parentThreadId == null) {
          const пошёл = await второйРаунд(
            {
              id: thread.id,
              projectId: thread.projectId ?? null,
              providerId: thread.providerId ?? null,
              environmentId: thread.environmentId ?? null,
            },
            lastAssistantText,
          );
          if (пошёл) return;
        }
        if (thread.visibility !== "visible") return;
        await запуститьПроверку(
          {
            id: thread.id,
            projectId: thread.projectId ?? null,
            providerId: thread.providerId ?? null,
            environmentId: thread.environmentId ?? null,
            parentThreadId: thread.parentThreadId ?? null,
          },
          "после",
        );
      } catch (error) {
        // Сбой второго мозга не должен мешать основной работе человека.
        bb.log.warn(
          `второй мозг пропущен: ${
            error instanceof Error ? error.message : String(error)
          }`,
        );
      }
    })();
  });

  bb.events.on("thread.failed", ({ thread }) => {
    void (async () => {
      try {
        const проверка = await хранилище.get<Проверка>(
          `${КЛЮЧ_ПРОВЕРКИ}${thread.id}`,
        );
        if (проверка === undefined) return;
        await хранилище.delete(`${КЛЮЧ_ПРОВЕРКИ}${thread.id}`);
        // Метку на родителе тоже снимаем: иначе один упавший проверяющий
        // навсегда закрывает этому треду дорогу ко второму мозгу.
        for (const м of ["рано", "после"]) {
          await хранилище.delete(`${КЛЮЧ_ПРОВЕРКИ}parent:${проверка.parentThreadId}:${м}`);
        }
        // Не состоявшаяся проверка бюджета не тратит, иначе кончившийся лимит
        // проверяющего выключает второй мозг на сутки вперёд.
        const бюджет = await хранилище.get<Бюджет>(КЛЮЧ_БЮДЖЕТА);
        const возврат = вернутьБюджет(бюджет);
        if (возврат !== undefined) await хранилище.set(КЛЮЧ_БЮДЖЕТА, возврат);
        // Падение проверяющего (кончился лимит, оборвалась связь) не повод
        // дёргать человека: каждый десятый дочерний тред падает.
        bb.log.info(`второй мозг: проверка ${thread.id} не состоялась, бюджет возвращён`);
      } catch {
        /* тишина намеренно: это уже путь обработки ошибки */
      }
    })();
  });
}
