/**
 * Паритет лимитов: у Claude и Codex расход должен гореть параллельно.
 *
 * Повод (директива Артёма 14.09.2026). У него две подписки, и они тратились
 * вразнобой: 13% недельного лимита Claude против 34% у Codex при одинаковом
 * сроке сброса через пять дней. Второй мозг при этом продолжал звать на дорогие
 * классы старшую модель Codex, то есть гнал перекос дальше. К концу недели у
 * одного провайдера остаётся запас, который сгорит нетронутым, а у второго
 * работа встаёт.
 *
 * Правило: разница в 5 процентных пунктов допустима, больше нет. Пока
 * проверяющий обогнал автора, его берегут: модель на ступень ниже, а при
 * сильном перекосе дешёвые классы пропускаются вовсе. Дорогой класс (деньги,
 * необратимое, диагностика) не отключается НИКОГДА: там ошибка стоит больше
 * любой экономии лимита, и проверка идёт младшей моделью.
 *
 * Симметрия обязательна: отставший проверяющий, наоборот, догружается старшей
 * моделью там, где обычно шла младшая. Правило про параллельный расход не
 * односторонний тормоз, иначе оно само создаёт перекос в другую сторону.
 *
 * Сравниваются НЕДЕЛЬНЫЕ окна: пятичасовое окно Claude восстанавливается
 * четыре раза в сутки, и выравнивать работу по нему бессмысленно.
 */

/** Окно лимита в том виде, в каком его отдаёт плагин «Лимиты» (bb limits --json). */
export interface ОкноЛимита {
  ключ: string;
  подпись: string;
  процент: number | null;
  сбросВ: number | null;
  важность: string | null;
}

export interface ЛимитыПровайдера {
  провайдер: string;
  подпись: string;
  окна: ОкноЛимита[];
  ошибка: string | null;
  снято: number;
}

export interface СнимокЛимитов {
  провайдеры: ЛимитыПровайдера[];
  обновлено: number | null;
}

/** Допустимая разница расхода между провайдерами, процентные пункты. */
export const ДОПУСК = 5;

/**
 * Разрыв, после которого дешёвым классам проверяющего не дают вовсе.
 *
 * Понижения модели на такой разнице мало: младшая модель дешевле, но не
 * бесплатна, а разрыв в двадцать пунктов на недельном окне это примерно полтора
 * дня работы отстающего провайдера.
 */
export const СИЛЬНЫЙ_ПЕРЕКОС = 20;

/** Расход, при котором проверяющего не зовут вовсе: тред всё равно упадёт. */
export const ПОЧТИ_ВЫБРАН = 95;

/** Снимок старше этого срока о сегодняшнем расходе не говорит ничего. */
export const СРОК_ГОДНОСТИ_СНИМКА = 30 * 60 * 1000;

/**
 * Сброс ближе этого срока обнуляет перекос сам.
 *
 * Перегруженный провайдер, у которого окно закрывается через несколько часов,
 * беречь незачем: к утру его процент станет нулём, а сэкономленные проверки
 * уже не вернуть.
 */
export const БЛИЗКИЙ_СБРОС = 12 * 60 * 60 * 1000;

export type РежимБаланса =
  | "неизвестно"
  | "паритет"
  | "беречь"
  | "беречь-сильно"
  | "стоп"
  | "догружать";

export interface Баланс {
  режим: РежимБаланса;
  /** Недельный расход автора и проверяющего, проценты. */
  расходАвтора: number | null;
  расходПроверяющего: number | null;
  /** Проверяющий минус автор: плюс значит, что проверяющего надо беречь. */
  разрыв: number | null;
  почему: string;
}

/** Провайдер лимитов, который соответствует провайдеру треда в bb. */
export function провайдерЛимитов(providerId: string): "claude" | "codex" | null {
  if (providerId === "claude-code" || providerId === "anthropic") return "claude";
  if (providerId === "codex") return "codex";
  return null;
}

/** Недельное ли это окно. У Codex ключ «primary», поэтому судим и по подписи. */
function недельное(окно: ОкноЛимита): boolean {
  if (/^недел/i.test(окно.подпись)) return true;
  return /(weekly|seven_day)/i.test(окно.ключ);
}

/**
 * Недельный расход провайдера: самое загруженное живое окно.
 *
 * У Claude недельных окон несколько (общее и привязанное к модели). Берётся
 * максимум, потому что упор в любое из них останавливает работу, а не среднее
 * по ним.
 */
export function недельныйРасход(
  провайдер: ЛимитыПровайдера | undefined,
  сейчас = Date.now(),
): { процент: number; сбросВ: number | null } | null {
  if (провайдер === undefined) return null;
  let лучшее: { процент: number; сбросВ: number | null } | null = null;
  for (const окно of провайдер.окна) {
    if (!недельное(окно)) continue;
    if (окно.процент === null || !Number.isFinite(окно.процент)) continue;
    // Окно, чей срок уже наступил, обнулилось: его прежний процент не расход.
    if (окно.сбросВ !== null && окно.сбросВ <= сейчас) continue;
    if (лучшее === null || окно.процент > лучшее.процент) {
      лучшее = { процент: окно.процент, сбросВ: окно.сбросВ };
    }
  }
  return лучшее;
}

function найти(
  снимок: СнимокЛимитов,
  имя: "claude" | "codex",
): ЛимитыПровайдера | undefined {
  return снимок.провайдеры.find((п) => п.провайдер === имя);
}

/**
 * Сравнение расхода автора и проверяющего.
 *
 * Возвращает «неизвестно» при любой неполноте: нет снимка, он протух, у одного
 * из провайдеров нет живого недельного окна. Неизвестность не должна менять
 * поведение пары — иначе выключенный плагин лимитов молча отключил бы второй
 * мозг.
 */
export function балансЛимитов(args: {
  снимок: СнимокЛимитов | null;
  провайдерАвтора: string;
  провайдерПроверяющего: string;
  сейчас?: number;
}): Баланс {
  const сейчас = args.сейчас ?? Date.now();
  const пусто = (почему: string): Баланс => ({
    режим: "неизвестно",
    расходАвтора: null,
    расходПроверяющего: null,
    разрыв: null,
    почему,
  });

  if (args.снимок === null) return пусто("расход лимитов неизвестен");
  const обновлено = args.снимок.обновлено;
  if (обновлено === null || сейчас - обновлено > СРОК_ГОДНОСТИ_СНИМКА) {
    return пусто("снимок лимитов устарел, сравнивать нечего");
  }
  const свой = провайдерЛимитов(args.провайдерАвтора);
  const чужой = провайдерЛимитов(args.провайдерПроверяющего);
  if (свой === null || чужой === null || свой === чужой) {
    return пусто("расход этой пары провайдеров не измеряется");
  }

  const автор = недельныйРасход(найти(args.снимок, свой), сейчас);
  const проверяющий = недельныйРасход(найти(args.снимок, чужой), сейчас);
  if (автор === null || проверяющий === null) {
    return пусто("недельного окна нет у одного из провайдеров");
  }

  const разрыв = Math.round(проверяющий.процент - автор.процент);
  const цифры = `${Math.round(автор.процент)}% у автора против ${Math.round(проверяющий.процент)}% у проверяющего`;
  const общее = {
    расходАвтора: Math.round(автор.процент),
    расходПроверяющего: Math.round(проверяющий.процент),
    разрыв,
  };

  if (проверяющий.процент >= ПОЧТИ_ВЫБРАН) {
    return {
      ...общее,
      режим: "стоп",
      почему: `недельный лимит проверяющего выбран на ${Math.round(проверяющий.процент)}%: запускать его сейчас значит плодить падающие треды`,
    };
  }

  // Перекос, который вот-вот обнулится сам, экономии не требует.
  const перегруженный = разрыв > 0 ? проверяющий : автор;
  const близкийСброс =
    перегруженный.сбросВ !== null &&
    перегруженный.сбросВ - сейчас <= БЛИЗКИЙ_СБРОС;
  if (Math.abs(разрыв) > ДОПУСК && близкийСброс) {
    return {
      ...общее,
      режим: "паритет",
      почему: `разрыв ${Math.abs(разрыв)} п.п. (${цифры}), но окно перегруженного закрывается меньше чем через ${Math.round(БЛИЗКИЙ_СБРОС / 3_600_000)} ч и обнулит его само`,
    };
  }

  if (разрыв > СИЛЬНЫЙ_ПЕРЕКОС) {
    return {
      ...общее,
      режим: "беречь-сильно",
      почему: `проверяющий обогнал автора на ${разрыв} п.п. (${цифры}): берегу его лимит до выравнивания`,
    };
  }
  if (разрыв > ДОПУСК) {
    return {
      ...общее,
      режим: "беречь",
      почему: `проверяющий обогнал автора на ${разрыв} п.п. (${цифры}): ступень мощности ниже`,
    };
  }
  if (разрыв < -ДОПУСК) {
    return {
      ...общее,
      режим: "догружать",
      почему: `проверяющий отстаёт на ${Math.abs(разрыв)} п.п. (${цифры}): его лимит можно тратить свободнее`,
    };
  }
  return {
    ...общее,
    режим: "паритет",
    почему: `расход идёт параллельно, разница ${Math.abs(разрыв)} п.п. (${цифры})`,
  };
}
